"""Build the CLM debug recorder (testing only, never shipped) and install it into the game.

    python debug/build_recorder.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

Makes `CLM - Debug Recorder.esp` (ESL; masters Fallout4.esm and the main plugin): one start-game-enabled quest
running A1ALMDBG_RecorderScript. Its watch lists are generated from the main plugin in the game's Data folder, so
re-run this after adding loose mods, unlock holotapes, unlock perks or configuration globals:
- items: A1ALMMISC_LooseMod_*, A1ALMMISC_Unlock_* (unlock holotapes) and A1ALMMISC_Catalyst_*
- perks: A1ALMPERK_Unlock_* and the loot perk
- globals: every GLOB in the main plugin
- actor values: VALUES below (vanilla), to see legendaries take effect on the player
Then compiles the script (debug build, traces kept), installs the .pex into Data/Scripts, and keeps copies of the
plugin and .pex in debug/. Turn Papyrus logging on with `python -m ack papyrus-log on`; read the log with
debug/read_log.py.

It also installs debug builds of CLM's effect scripts (TRACED) over the release ones in Data/Scripts. Their Log()
lines (DebugOnly, so release builds strip them) say what each scripted legendary did: started, triggered, a failed
chance roll, who it hit. They write to the recorder's log only, so without the recorder they do nothing.

    python debug/build_recorder.py --game "..." --remove

puts the release scripts back (from data/SCRIPTS) and deletes the recorder plugin and script from Data.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
MAIN = 'Custom Legendary Modifications Remade.esp'
RECORDER = 'CLM - Debug Recorder.esp'
QUEST = 'A1ALMDBG_Recorder'
SCRIPT = 'A1ALMDBG_RecorderScript'
VALUES = ['JumpHeightMult', 'SpeedMult', 'Strength', 'DamageResist', 'EnergyResist', 'RadResistExposure',
          'CarryWeight']  # not Health/ActionPoints: they change constantly in play
TRACED = ['A1ALMMGEF_BurstFireEffect', 'A1ALMMGEF_CinematicCameraEffect', 'A1ALMMGEF_DragonDashEffect',
          'A1ALMMGEF_DrainOnHitScript', 'A1ALMMGEF_ExplodeAfterDeathScript', 'A1ALMMGEF_FactionFriendEffect',
          'A1ALMMGEF_OnHealthUseStim', 'A1ALMMGEF_OnHitArmourEffect', 'A1ALMMGEF_OnKillArmourEffect',
          'A1ALMMGEF_OnMeleeEffect', 'A1ALMMGEF_PercentDamageEffect', 'A1ALMMGEF_CleaveEffect',
          'A1ALMMGEF_NecromancerEffect', 'A1ALMMGEF_RisenEffect', 'A1ALMMGEF_PolymorphEffect', 'A1ALMMGEF_ShrinkEffect',
          'A1ALMMGEF_ExplodeOnHitEffect']


def watch_lists(main_path: Path, ack: Path) -> tuple[list[str], list[str], list[str]]:
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin
    p = Plugin.load(main_path)
    own = [r for r in p.records() if p.is_own(r.formid)]
    items = sorted(r.edid for r in own if r.edid.startswith(('A1ALMMISC_LooseMod_', 'A1ALMMISC_Unlock_', 'A1ALMMISC_Catalyst_')))
    perks = sorted(r.edid for r in own if r.edid.startswith(('A1ALMPERK_Unlock_', 'A1ALMPERK_Loot')))
    globs = sorted(r.edid for r in own if r.sig == 'GLOB')
    return items, perks, globs


def spec(items: list[str], perks: list[str], globs: list[str]) -> str:
    def arr(names: list[str]) -> str:
        return ','.join('@' + n for n in names)
    lines = [
        '# Generated by debug/build_recorder.py - do not edit',
        f'file | {RECORDER}',
        'master | Fallout4.esm',
        f'master | {MAIN}',
        'header | CNAM | Deadmansprice',
        'header | SNAM | CLM debug recorder - testing only, not part of the mod.',
        f'new | QUST | {QUEST}',
        f'set | {QUEST} | FULL | CLM Debug Recorder',
        f'set | {QUEST} | DNAM\\Flags | 1',  # Start Game Enabled
        f'script | {QUEST} | {SCRIPT}',
    ]
    for name, values in (('WatchItems', items), ('WatchPerks', perks), ('WatchGlobals', globs),
                         ('WatchValues', VALUES)):
        if values:
            lines.append(f'prop | {QUEST} | {SCRIPT} | {name} | Array of Object | {arr(values)}')
        else:  # drop a list left over from an earlier build (its records may be gone)
            lines.append(f'propremove | {QUEST} | {SCRIPT} | {name}')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', help='AgentCreationKit checkout (not needed with --remove)')
    ap.add_argument('--game', required=True, help='Fallout 4 folder')
    ap.add_argument('--remove', action='store_true', help='uninstall: release scripts back, recorder deleted')
    a = ap.parse_args()
    data = Path(a.game) / 'Data'
    if a.remove:
        for name in TRACED:
            shutil.copy(REPO / 'data' / 'SCRIPTS' / f'{name}.pex', data / 'Scripts' / f'{name}.pex')
        for f in (data / RECORDER, data / 'Scripts' / f'{SCRIPT}.pex'):
            f.unlink(missing_ok=True)
        print(f'release scripts restored ({len(TRACED)}); {RECORDER} and its script removed from {data}')
        return
    if not a.ack:
        ap.error('--ack is required')
    ack = Path(a.ack)

    items, perks, globs = watch_lists(data / MAIN, ack)
    print(f'watching {len(items)} items, {len(perks)} perks, {len(globs)} globals')
    spec_path = HERE / 'recorder_spec.txt'
    spec_path.write_text(spec(items, perks, globs), encoding='utf8')

    cmd = [sys.executable, '-m', 'ack', 'xedit', 'run', 'build', MAIN, '--save', '--timeout', '300',
           '--param', f'SPEC={spec_path}']
    if (data / RECORDER).exists():
        cmd += ['--also-load', RECORDER]  # update it in place rather than creating it again
    r = subprocess.run(cmd, cwd=ack, capture_output=True, text=True)
    print(r.stdout.strip())
    runs = sorted((ack / 'private' / 'runs').glob('*-build'))
    result = (runs[-1] / 'result.txt').read_text(encoding='utf8') if runs else ''
    print(result.splitlines()[0] if result else 'no result')
    if r.returncode != 0 or ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit(result or r.stderr)

    subprocess.run([sys.executable, str(REPO / 'tools' / 'papyrus' / 'compile.py'), '--game', a.game, '--debug',
                    SCRIPT] + TRACED, check=True, stdout=subprocess.DEVNULL)
    for name in [SCRIPT] + TRACED:
        shutil.copy(HERE / 'SCRIPTS' / f'{name}.pex', data / 'Scripts' / f'{name}.pex')
    shutil.copy(data / RECORDER, HERE / RECORDER)
    print(f'installed {RECORDER}, Scripts/{SCRIPT}.pex and {len(TRACED)} traced effect scripts into {data}')


if __name__ == '__main__':
    main()
