"""Coloured laser disintegration: Energized lasers and Disintegratin' (Green) turn their kills to ash in their colour.

    python tools/assets/disintegration_colors.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

Vanilla has two laser disintegrations, red (CritLaser: laser guns) and blue (CritLaserLtBlue: Institute guns). Both
are the same AttachAshPile script effect with two properties: a glow shader on the dying body (EFSH, coloured by a
gradient texture and an edge colour) and the ash pile left behind (ACTI; AshPile01.nif and AshPileBlue.nif differ
only in their shader's emissive colour). Energized lasers only replaced the beam, so kills disintegrated in the base
gun's colour (blue on an Institute gun, whatever the beam).

For each CLM laser colour (tools/assets/laser_colors.py: hue rotations of vanilla red) this makes:
  textures\\Effects\\Gradients\\CLM\\CritLaser<Colour>Grad.dds   CritLaserGrad.dds, hue-rotated
  meshes\\Effects\\CLM\\AshPile<Colour>.nif                      AshPile01.nif, emissive colour hue-rotated
  A1ALMEFSH_CritLaser<Colour>   copy of CritLaserFXS: the new gradient, edge colour rotated
  A1ALMACTI_AshPile<Colour>     copy of AshPile01 with the new model
  A1ALMMGEF_CritLaser<Colour>Effect, A1ALMSPEL_CritLaser<Colour>   copies of CritLaserEffect / CritLaser using them
Each Energized colour then sets the weapon's critical effect (CritEffect SET) to its colour - Red and Blue to the
vanilla red and blue ones - and Disintegratin' (Green), which borrowed the plasma "goo" effect, uses the green ones.
New assets: PC and Xbox only (PlayStation mods may not add assets).
"""
from __future__ import annotations

import argparse
import colorsys
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(HERE))
MAIN = 'Custom Legendary Modifications Remade.esp'
RED_GLOW = (0.718, 0.067, 0.0)          # AshPile01.nif BSLightingShaderProperty emissive colour
RED_EDGE = (254, 152, 118)              # CritLaserFXS edge colour
CRIT_TEMPLATE = 'A1ALMOMOD_Legendary_Weapon_Contact_Disintegration_Base_Red'   # an OMOD with a CritEffect property
DISINTEGRATIN_GREEN = 'A1ALMOMOD_Legendary_Weapon_Contact_Disintegration_Variant_Green'
VANILLA = {'Red': 'CritLaser', 'LtBlue': 'CritLaserLtBlue'}


def edids(c: str) -> dict:
    return {'efsh': f'A1ALMEFSH_CritLaser{c}', 'acti': f'A1ALMACTI_AshPile{c}',
            'mgef': f'A1ALMMGEF_CritLaser{c}Effect', 'spel': f'A1ALMSPEL_CritLaser{c}'}


def rotate(rgb, deg):
    h, s, v = colorsys.rgb_to_hsv(*rgb)
    return colorsys.hsv_to_rgb((h + deg / 360) % 1, s, v)


def make_assets(game: Path, outs: list[Path]) -> None:
    from ack.archive import extract_general, extract_textures
    from laser_colors import COLORS, read_dds_bgra, rotate_hue, write_dds_bgra
    data = game / 'Data'
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        extract_general(data / 'Fallout4 - Meshes.ba2', ['meshes\\effects\\ashpile01.nif'], tmp)
        for ba2 in sorted(data.glob('Fallout4 - Textures*.ba2')):
            extract_textures(ba2, ['textures\\effects\\gradients\\critlasergrad.dds'], tmp)
        nif = (tmp / 'Meshes' / 'Effects' / 'AshPile01.nif').read_bytes()
        grad = read_dds_bgra(tmp / 'Textures' / 'Effects' / 'Gradients' / 'CritLaserGrad.dds')
    at = [o for o in range(len(nif) - 11)
          if all(abs(x - y) < 5e-4 for x, y in zip(struct.unpack_from('<3f', nif, o), RED_GLOW))]
    assert len(at) == 1, f'emissive colour found {len(at)} times in AshPile01.nif'
    for c, deg in COLORS.items():
        g = rotate_hue(grad, deg)
        m = bytearray(nif)
        struct.pack_into('<3f', m, at[0], *rotate(RED_GLOW, deg))
        for out in outs:
            write_dds_bgra(out / 'Textures' / 'Effects' / 'Gradients' / 'CLM' / f'CritLaser{c}Grad.dds', g)
            (out / 'Meshes' / 'Effects' / 'CLM').mkdir(parents=True, exist_ok=True)
            (out / 'Meshes' / 'Effects' / 'CLM' / f'AshPile{c}.nif').write_bytes(bytes(m))
    print(f'{len(COLORS)} gradients and ash piles written to', ', '.join(map(str, outs)))


def run(ack: Path, script: str, *args: str) -> str:
    subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', script, MAIN, '--save', '--timeout', '600', *args],
                   cwd=ack, capture_output=True, text=True)
    out = sorted((ack / 'private' / 'runs').glob(f'*-{script}'))[-1] / 'result.txt'
    text = out.read_text(encoding='utf8')
    print(text.splitlines()[0])
    return text


def make_records(ack: Path, game: Path) -> None:
    from laser_colors import COLORS
    s = ['# Generated by tools/assets/disintegration_colors.py', f'file | {MAIN}']
    for c, deg in COLORS.items():
        e = edids(c)
        edge = [round(x * 255) for x in rotate(tuple(v / 255 for v in RED_EDGE), deg)]
        s += [f'copy | @CritLaserFXS | {e["efsh"]}',
              f'set | {e["efsh"]} | NAM8 | Effects\\Gradients\\CLM\\CritLaser{c}Grad.dds',
              f'set | {e["efsh"]} | DNAM\\Data\\Edge Effect - Color\\Red | {edge[0]}',
              f'set | {e["efsh"]} | DNAM\\Data\\Edge Effect - Color\\Green | {edge[1]}',
              f'set | {e["efsh"]} | DNAM\\Data\\Edge Effect - Color\\Blue | {edge[2]}',
              f'copy | @AshPile01 | {e["acti"]}',
              f'set | {e["acti"]} | Model\\MODL | Effects\\CLM\\AshPile{c}.nif', f'remove | {e["acti"]} | Model\\MODT',
              f'copy | @CritLaserEffect | {e["mgef"]}',
              f'prop | {e["mgef"]} | AttachAshPile | MagicEffectShader | Object | @{e["efsh"]}',
              f'prop | {e["mgef"]} | AttachAshPile | AshPileObject | Object | @{e["acti"]}',
              f'copy | @CritLaser | {e["spel"]}']
    green = edids('Green')
    mg = 'A1ALMMGEF_Target_Effect_Hostile_Disintegration_Green'
    s += [f'prop | {mg} | AttachAshPile | MagicEffectShader | Object | @{green["efsh"]}',
          f'prop | {mg} | AttachAshPile | AshPileObject | Object | @{green["acti"]}',
          'set | A1ALMEnch_FaF_Contact_Custom_Effect_Disintegration_Green | FULL | CLM: Disintegration (Green)']
    spec = HERE / 'disintegration_colors.spec'
    spec.write_text('\n'.join(s) + '\n', encoding='utf8')
    result = run(ack, 'build', '--param', f'SPEC={spec}')
    if ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit('\n'.join(l for l in result.splitlines() if 'ERR' in l))

    # the spell copies still use the vanilla effect: point each at its colour's effect
    from ack.plugin import Plugin
    data = game / 'Data'
    p = Plugin.load(data / MAIN)
    fo = Plugin.load(data / 'Fallout4.esm')
    old = struct.pack('<I', fo.by_edid('CritLaserEffect').formid)
    for c in COLORS:
        spel = p.by_edid(edids(c)['spel'])
        new = struct.pack('<I', p.by_edid(edids(c)['mgef']).formid)
        n = 0
        for sub in spel.subrecords:
            if sub.sig == 'EFID' and sub.data == old:
                sub.data = new
                n += 1
        assert n == 1, (c, n)
        spel.mark_dirty()
    p.save(data / MAIN)

    # weapon legendaries: each laser colour sets its own critical effect (skipped where already set: re-runs)
    def spell_fid(c: str) -> int:
        return (fo if c in VANILLA else p).by_edid(VANILLA.get(c) or edids(c)['spel']).formid

    def sets(om: str, fid: int) -> bool:
        return struct.pack('<I', fid) in p.by_edid(om).get('DATA').data

    lines = ['# Generated by tools/assets/disintegration_colors.py']
    for c in [*COLORS, *VANILLA]:
        om = f'A1ALMOMOD_Legendary_Weapon_Energized_Laser_{c}'
        if not sets(om, spell_fid(c)):
            lines.append(f'prop.add | {om} | CritEffect | SET | 431 | {CRIT_TEMPLATE} | @{VANILLA.get(c) or edids(c)["spel"]}')
    if not sets(DISINTEGRATIN_GREEN, spell_fid('Green')):
        lines += [f'prop.remove | {DISINTEGRATIN_GREEN} | CritEffect',
                  f'prop.add | {DISINTEGRATIN_GREEN} | CritEffect | SET | 431 | {CRIT_TEMPLATE} | @{green["spel"]}']
    edits = HERE / 'disintegration_colors_edits.txt'
    edits.write_text('\n'.join(lines) + '\n', encoding='utf8')
    result = run(ack, 'apply_edits', '--param', f'EDITS={edits}')
    if 'FAIL' in result:
        raise SystemExit('\n'.join(l for l in result.splitlines() if 'FAIL' in l))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    ap.add_argument('--assets-only', action='store_true')
    a = ap.parse_args()
    ack, game = Path(a.ack), Path(a.game)
    sys.path.insert(0, str(ack))
    make_assets(game, [REPO / 'data', game / 'Data'])
    if not a.assets_only:
        make_records(ack, game)


if __name__ == '__main__':
    main()
