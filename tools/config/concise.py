"""CLM 2.1 concise view (docs/CONCISE_VIEW_PLAN.md; author's decisions 2026-10-14): the workbench shows one balanced
legendary per group of similar effects (tools/config/concise_groups.py); the rest of each group is hidden until the
player shows it.

    python tools/config/concise.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

Run after tools/config/settings.py (the "Show all" and "Hidden legendaries drop too" settings), tools/loot/generate.py
(it rewrites the loot recipes' conditions) and tools/config/picker.py. Safe to re-run. Then tools/config/mcm.py.

- A hidden legendary's costly and FREE recipes also need one of: "Show all legendaries" (setting item or global), or
  its group's "CLM Group" item (or global, from the F4SE menu). Loot recipes (_Unlocked) also accept "Hidden
  legendaries drop too". Records only, so PlayStation works the same (items at the chemistry station).
- Spawns: each creature's Legendary and Boss spawns form one group; the plain Random spawns stay.
- Existing saves keep everything shown, as before 2.1: a start-game quest (PC/Xbox) gives "Show all legendaries" to
  a save that is past the Vault 111 exit (MQ102 stage 6). New games start with the concise view. PlayStation saves
  cannot run it: players there craft "Show all legendaries" if they want the full list back.
- Nothing is deleted: hidden legendaries stay in the plugin, and gear that has them keeps working.
"""
from __future__ import annotations

import argparse
import re
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / 'tools' / 'loot'))
sys.path.insert(0, str(HERE))
import generate  # noqa: E402
from concise_groups import WEAPON, ARMOUR  # noqa: E402

MAIN = generate.MAIN
OM = 'A1ALMOMOD_Legendary_'
SPAWNS = ('weapon', 'Legendary and boss spawns')
CATEGORY = ('A1ALMKW_RecipeFilter_Groups', 'CLM Groups')
TEMPLATE_MISC = '@miscmod_mod_RailwayRifle_Scope_ScopeShort_Recon'
MODEL = 'Props\\Holotape_Prop.nif'
QUEST, SCRIPT = 'A1ALMQUST_ConciseMigrate', 'A1ALMConciseMigrateScript'
FN_GET_ITEM_COUNT, FN_GET_GLOBAL_VALUE = 47, 74
OP_EQ, OP_GE, FLAG_OR = 0, 3 << 5, 1


def groups() -> list[tuple[str, str]]:
    return [('weapon', g[0]) for g in WEAPON] + [('armor', g[0]) for g in ARMOUR] + [SPAWNS]


def item(kind: str, group: str) -> str:
    return f'A1ALMGRP_{kind.capitalize()}_{generate.slug(group)}'


def glob(kind: str, group: str) -> str:
    return f'A1ALMGRPG_{kind.capitalize()}_{generate.slug(group)}'


def label(kind: str, group: str) -> str:
    return f'CLM Group: {group}' + ('' if (kind, group) == SPAWNS else f' ({"Weapon" if kind == "weapon" else "Armour"})')


def hidden(p) -> dict[str, tuple[str, str]]:
    """Hidden legendary editor ID -> its group, read from the plugin (names in concise_groups.py, kind from the mod's
    form type: some Weapon_ editor IDs are armour mods)."""
    show_op = p.by_edid('A1ALMSET_ShowOP').formid
    omods = {r.formid: r for r in p.records('OMOD') if p.is_own(r.formid) and (r.edid or '').startswith(OM)}
    op = set()
    for c in p.records('COBJ'):
        cn = c.get('CNAM')
        if cn and struct.unpack('<I', cn.data)[0] in omods and any(
                s.sig == 'CTDA' and struct.unpack_from('<HxxI', s.data, 8) == (FN_GET_ITEM_COUNT, show_op)
                for s in c.subrecords):
            op.add(struct.unpack('<I', cn.data)[0])
    index: dict[tuple[str, str], list[str]] = {}
    spawn_tiers = []
    for fid, r in omods.items():
        full = r.get('FULL')
        if full is None or fid in op:
            continue
        name = re.sub(r'^[CZ]LM: ', '', full.zstring)
        form = {b'WEAP': 'weapon', b'ARMO': 'armor'}.get(r.get('DATA').data[10:14])
        index.setdefault((form, name), []).append(r.edid)
        if '_Custom_Spawning_' in r.edid and re.search(r'Legendary|Boss', name):
            spawn_tiers.append(r.edid)
    out = {}
    for kind, table in (('weapon', WEAPON), ('armor', ARMOUR)):
        for group, _, shown, members in table:
            for name in [shown] + members:
                found = sorted(index.get((kind, name), []))   # two records can share a name (Highlighting)
                assert found, f'{kind} "{name}" not found'
                for e in (found if name != shown else found[1:]):
                    out[e] = (kind, group)
    for e in spawn_tiers:
        out[e] = SPAWNS
    return out


def write_spec() -> Path:
    s = ['# Generated by tools/config/concise.py - do not edit', f'file | {MAIN}', f'new | KYWD | {CATEGORY[0]}',
         f'set | {CATEGORY[0]} | FULL | {CATEGORY[1]}']
    for k, g in groups():
        e = item(k, g)
        s += [f'copy | {TEMPLATE_MISC} | {e}', f'set | {e} | FULL | {label(k, g)}', f'set | {e} | Model\\MODL | {MODEL}',
              f'remove | {e} | Model\\MODT', f'remove | {e} | KWDA', f'remove | {e} | KSIZ',
              f'set | {e} | DATA\\Weight | 0', f'set | {e} | DATA\\Value | 0', f'new | COBJ | co_{e}', f'new | GLOB | {glob(k, g)}']
    s += ['prunerecords | A1ALMGRP_', 'prunerecords | co_A1ALMGRP_',
          f'new | QUST | {QUEST}', f'set | {QUEST} | FULL | CLM Concise View Migration',
          f'set | {QUEST} | DNAM\\Flags | 1',  # start game enabled: also starts once in saves made before 2.1
          f'script | {QUEST} | {SCRIPT}',
          f'prop | {QUEST} | {SCRIPT} | ShowAll | Object | @A1ALMSET_ShowAll',
          f'prop | {QUEST} | {SCRIPT} | MQ102 | Object | @MQ102']
    path = HERE / 'concise.spec'
    path.write_text('\n'.join(s) + '\n', encoding='utf8')
    return path


MIGRATE_SOURCE = f'''Scriptname {SCRIPT} extends Quest
{{CLM 2.1, PC/Xbox: the concise view hides similar legendaries, but saves made before 2.1 keep everything shown, as
before. This start-game quest also starts once in older saves: if the player is past the Vault 111 exit (MQ102
stage 6), it gives "Show all legendaries". A new game starts before that point and gets the concise view.
Generated by tools/config/concise.py.}}

MiscObject Property ShowAll Auto Const Mandatory
Quest Property MQ102 Auto Const Mandatory

bool done

Event OnInit()
	If done
		Return
	EndIf
	done = true
	If MQ102.GetStageDone(6)
		Actor player = Game.GetPlayer()
		If player.GetItemCount(ShowAll) == 0
			player.AddItem(ShowAll, 1, true)
		EndIf
	EndIf
EndEvent
'''


def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin
    from ack.plugin.records import Subrecord
    from settings import ITEMS, setting_global, ctda, MCM_GLOBAL, CATEGORY as SETTINGS_CATEGORY

    p = Plugin.load(data / MAIN)
    fid = lambda e: p.by_edid(e).formid
    chem = Plugin.load(data / 'Fallout4.esm').by_edid('WorkbenchChemlab').formid
    kw = p.by_edid(CATEGORY[0])
    kw.subrecords[:] = [kw.subrecords[0], Subrecord('CNAM', bytes.fromhex('ffffff00')),
                        Subrecord('TNAM', struct.pack('<I', 9)), kw.get('FULL')]   # 9 = Recipe Filter
    kw.mark_dirty()
    for k, g in groups():
        r = p.by_edid(glob(k, g))
        if r.get('FLTV') is None:
            r.subrecords[:] = [r.subrecords[0], Subrecord('FNAM', b'f'), Subrecord('FLTV', struct.pack('<f', 0.0))]
            r.mark_dirty()
    all_item, all_glob = fid(ITEMS['all'][0]), fid(setting_global('all'))
    loot_item, loot_glob = fid(ITEMS['loothidden'][0]), fid(setting_global('loothidden'))
    mine = {all_item, all_glob, loot_item, loot_glob} | {fid(item(k, g)) for k, g in groups()} | \
        {fid(glob(k, g)) for k, g in groups()}
    # items and globals of groups that were renamed or merged away (pruned by the build): drop their conditions too
    own = len(p.masters)
    exists = {r.formid for r in p.records()}
    gone = lambda param: (param >> 24) == own and param not in exists

    members = hidden(p)
    count = {kg: 0 for kg in groups()}
    for kg in members.values():
        count[kg] += 1
    omod_of = {p.by_edid(e).formid: kg for e, kg in members.items()}
    changed = 0
    for c in p.records('COBJ'):
        cn = c.get('CNAM')
        if not cn or not p.is_own(c.formid) or c.edid.startswith(('co_A1ALMSET', 'co_A1ALMPICK', 'co_A1ALMGRP')):
            continue            # chemistry station recipes check these items for their own reasons
        subs = [s for s in c.subrecords if not (s.sig == 'CTDA' and (struct.unpack_from('<I', s.data, 12)[0] in mine or
                                                                     gone(struct.unpack_from('<I', s.data, 12)[0])))]
        kg = omod_of.get(struct.unpack('<I', cn.data)[0])
        if kg is not None:
            pairs = [(FN_GET_ITEM_COUNT, all_item), (FN_GET_GLOBAL_VALUE, all_glob),
                     (FN_GET_ITEM_COUNT, fid(item(*kg))), (FN_GET_GLOBAL_VALUE, fid(glob(*kg)))]
            if c.edid.endswith('_Unlocked'):
                pairs += [(FN_GET_ITEM_COUNT, loot_item), (FN_GET_GLOBAL_VALUE, loot_glob)]
            conds = [Subrecord('CTDA', ctda((OP_GE if fn == FN_GET_ITEM_COUNT else OP_EQ) |
                                            (FLAG_OR if i < len(pairs) - 1 else 0), 1.0, fn, param))
                     for i, (fn, param) in enumerate(pairs)]
            at = next(i for i, s in enumerate(subs) if s.sig == 'CNAM')
            subs[at:at] = conds
        if [s.data for s in subs] != [s.data for s in c.subrecords]:
            c.subrecords[:] = subs
            c.mark_dirty()
            changed += 1

    # the group items at the chemistry station
    mcm = p.by_edid(MCM_GLOBAL)
    for k, g in groups():
        e = item(k, g)
        r = p.by_edid(f'co_{e}')
        conds = [ctda(OP_EQ, 0.0, FN_GET_ITEM_COUNT, fid(e)), ctda(OP_EQ, 0.0, FN_GET_ITEM_COUNT, all_item),
                 ctda(OP_EQ, 0.0, FN_GET_GLOBAL_VALUE, all_glob)]
        if mcm is not None:
            conds.append(ctda(OP_EQ, 0.0, FN_GET_GLOBAL_VALUE, mcm.formid))
        names = sorted(re.sub(r'^[CZ]LM: ', '', p.by_edid(m).get('FULL').zstring) for m, x in members.items() if x == (k, g))
        shown = '' if (k, g) == SPAWNS else next(t[2] for t in (WEAPON if k == 'weapon' else ARMOUR) if t[0] == g)
        text = (f'Concise view: show the whole "{g}" group at the workbench. ' +
                (f'{shown} always shows; carrying this adds ' if shown else 'Carrying this adds ') + ', '.join(names) +
                '. Drop it to hide them again. Not needed with "Show all legendaries".')
        if len(text) > 900:
            text = text[:897] + '...'
        r.subrecords[:] = [r.subrecords[0], Subrecord('DESC', text.encode('cp1252') + b'\0'),
                           *[Subrecord('CTDA', d) for d in conds], Subrecord('CNAM', struct.pack('<I', fid(e))),
                           Subrecord('BNAM', struct.pack('<I', chem)), Subrecord('FNAM', struct.pack('<I', kw.formid)),
                           Subrecord('INTV', struct.pack('<HH', 1, 0))]
        r.mark_dirty()
    p.save(data / MAIN)
    print(f'{len(members)} legendaries hidden in {len(groups())} groups; {changed} recipes updated')
    for (k, g), n in count.items():
        print(f'  {label(k, g)}: {n} hidden')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, game = Path(a.ack), Path(a.game)
    (REPO / 'source' / 'User' / f'{SCRIPT}.psc').write_text(MIGRATE_SOURCE, encoding='utf8')
    subprocess.run([sys.executable, str(REPO / 'tools' / 'papyrus' / 'compile.py'), '--game', str(game), SCRIPT], check=True)
    (game / 'Data' / 'Scripts' / f'{SCRIPT}.pex').write_bytes((REPO / 'data' / 'SCRIPTS' / f'{SCRIPT}.pex').read_bytes())
    sys.path.insert(0, str(ack))
    generate.run_build(write_spec(), game / 'Data', ack)
    write_raw(game / 'Data', ack)


if __name__ == '__main__':
    main()
