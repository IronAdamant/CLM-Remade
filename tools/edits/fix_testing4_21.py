"""2.1: fourth round of fixes from the author's in-game testing (2026-10-16).

    python tools/edits/fix_testing4_21.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

- CQC (script only): the animation event is "WeaponFire"; "weaponFire" never arrived (names are case-sensitive).
- DragonBlade: Game.FindClosestActorFromRef returned the wielder itself, so no swing found an enemy; the dash script
  now searches by actor type keyword (its new ActorTypes property), as Cleavin' does.
- Necromancer's: the risen stood where they rose; they now walk to their target first and are foolhardy (Confidence 4).
- Cinematic Excellence: TEMPORARILY every kill (author's "CE Test"); its name says so. Set ChanceToCast back to 0.1 and
  the name back before release (docs/PLAN_2.1.md).
- Flamin': the flamer stream did no burning; it now carries the base game's Incendiary enchantment.
- Hello Neighbour! removed (author's decision): even neutral to the player's faction, Gunners kept attacking.
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
OM = 'A1ALMOMOD_Legendary_'
PLAYER_FACTION, AGGRESSION, CONFIDENCE = 0x1C21C, 0x2BC, 0x2BD
ACTOR_TYPES = [0x13794, 0x13795, 0x13798, 0x2CB73, 0x6D7B6, 0xEAFB7, 0xB2BF3, 0x2CB71, 0x10C3CE, 0x317AA]
CE_TEST = True       # Cinematic Excellence on every kill while the author tests it
CUT = ['co_A1ALMOMOD_Legendary_Armor_HelloNeighbour', 'co_A1ALMOMOD_Legendary_Armor_HelloNeighbourFREE',
       'co_A1ALMOMOD_Legendary_Armor_HelloNeighbour_Unlocked', 'A1ALMOMOD_Legendary_Armor_HelloNeighbour',
       'A1ALMMISC_LooseMod_Armor_HelloNeighbour', 'A1ALMEnch_Constant_Effect_Custom_Effect_HelloNeighbour',
       'A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_HelloNeighbour', 'A1ALMPERK_Legendary_Hidden_Armor_HelloNeighbour',
       'A1ALMSPEL_Ability_Armor_HelloNeighbour', 'A1ALMMGEF_Constant_Effect_Armor_HelloNeighbour']
EDITS = [
    f'prop.add | {OM}Weapon_Flaming | Enchantments | ADD | 431 | {OM}Weapon_Bloodlust | @dtFireEnchFlameChanceAlways',
    f"text.set | {OM}Weapon_Flaming | DESC | This mod turns your weapon into one of the favourite tools in the "
    "pyromaniac's arsenal: it shoots a flamer stream, fully automatic, so hold the trigger, and sets targets on fire "
    "like the Incendiary legendary. Your ammo does not change.",
    *(['text.set | A1ALMOMOD_Legendary_Weapon_CinematicExcellence | FULL | CLM: Cinematic Excellence (CE Test)']
      if CE_TEST else []),
    *[f'rec.delete | {e}' for e in CUT],
]


def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin

    p = Plugin.load(data / MAIN)
    w = lambda s: struct.pack('<H', len(s)) + s.encode('ascii')
    obj = lambda f: b'\x01\x01' + struct.pack('<HhI', 0, -1, f)
    objs = lambda fs: b'\x0b\x01' + struct.pack('<I', len(fs)) + b''.join(struct.pack('<HhI', 0, -1, f) for f in fs)
    head = lambda script, n: struct.pack('<hhH', 6, 2, 1) + w(script) + b'\0' + struct.pack('<H', n)

    r = p.by_edid('A1ALMMGEF_Constant_Effect_Weapon_DragonBlade')
    r.set('VMAD', head('A1ALMMGEF_DragonDashEffect', 1) + w('ActorTypes') + objs(ACTOR_TYPES))
    r.mark_dirty()
    r = p.by_edid('A1ALMMGEF_Target_Effect_Risen')
    r.set('VMAD', head('A1ALMMGEF_RisenEffect', 4) + w('AllyFaction') + obj(PLAYER_FACTION) + w('Aggression') +
          obj(AGGRESSION) + w('Confidence') + obj(CONFIDENCE) + w('ActorTypes') + objs(ACTOR_TYPES))
    r.mark_dirty()
    r = p.by_edid('A1ALMMGEF_Constant_Effect_Weapon_CinematicExcellence')
    v = bytearray(r.get('VMAD').data)
    name = b'ChanceToCast'
    at = v.index(struct.pack('<H', len(name)) + name) + 2 + len(name)
    assert v[at] == 4
    struct.pack_into('<f', v, at + 2, 1.0 if CE_TEST else 0.1)
    r.set('VMAD', bytes(v))
    r.mark_dirty()
    p.save(data / MAIN)
    print('DragonBlade, Necromancer\'s and Cinematic Excellence written')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    path = HERE / 'fix_testing4_21.txt'
    path.write_text('# Generated by fix_testing4_21.py - edit that, not this file.\n' + '\n'.join(EDITS) + '\n', encoding='utf8')
    r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout', '900',
                        '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
    result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
    print(result.splitlines()[0])
    if ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit('\n'.join(l for l in result.splitlines() if l.startswith('ERROR')) + r.stderr)
    write_raw(data, ack)


if __name__ == '__main__':
    main()
