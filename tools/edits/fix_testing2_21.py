"""2.1: second round of fixes from the author's in-game testing (2026-10-15).

    python tools/edits/fix_testing2_21.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

- Rallyin': a concentration aura spell changed nothing on allies. Its spell is now fire-and-forget with 3-second
  effects that the aura casts again every second, the setup God Creator and Disheartenin' work with.
- Necromancer's: the risen go for the nearest enemy every few seconds (A1ALMMGEF_RisenEffect's ActorTypes), and at
  most three stand at once (A1ALMMGEF_NecromancerEffect).
- Breakin' and Enterin' removed (author's decision): the lock and terminal levels did not change. The game seems to
  read them from the Locksmith and Hacker perks themselves, and adding those perks by script could take away a rank
  the player bought. Fiddlin' covers lockpicking.
Then re-run the loot, picker, concise, MCM and recorder tools (the legendary list changed).
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
PLAYER_FACTION, AGGRESSION = 0x1C21C, 0x2BC
ACTOR_TYPES = [0x13794, 0x13795, 0x13798, 0x2CB73, 0x6D7B6, 0xEAFB7, 0xB2BF3, 0x2CB71, 0x10C3CE, 0x317AA]
RALLY = ['A1ALMMGEF_Aura_Rally_DamageResist', 'A1ALMMGEF_Aura_Rally_EnergyResist', 'A1ALMMGEF_Aura_Rally_AttackDamageMult']
CUT = ['co_A1ALMOMOD_Legendary_Armor_BreakingAndEntering', 'co_A1ALMOMOD_Legendary_Armor_BreakingAndEnteringFREE',
       'co_A1ALMOMOD_Legendary_Armor_BreakingAndEntering_Unlocked',
       'A1ALMOMOD_Legendary_Armor_BreakingAndEntering', 'A1ALMEnch_Constant_Effect_Custom_Effect_BreakingAndEntering',
       'A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_BreakingAndEntering',
       'A1ALMPERK_Legendary_Hidden_Armor_BreakingAndEntering']
EDITS = [
    'field.set | A1ALMSPEL_Aura_Rallying | SPIT\\Cast Type | Fire and Forget',
    *[f'field.set | {m} | Magic Effect Data\\DATA\\Casting Type | Fire and Forget' for m in RALLY],
    *[f'field.set | A1ALMSPEL_Aura_Rallying | Effects\\[{i}]\\EFIT\\Duration | 3' for i in range(len(RALLY))],
    *[f'rec.delete | {e}' for e in CUT],
]


def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin

    p = Plugin.load(data / MAIN)

    def wstr(s):
        return struct.pack('<H', len(s)) + s.encode('ascii')

    obj = lambda f: b'\x01\x01' + struct.pack('<HhI', 0, -1, f)
    objs = lambda fs: b'\x0b\x01' + struct.pack('<I', len(fs)) + b''.join(struct.pack('<HhI', 0, -1, f) for f in fs)
    r = p.by_edid('A1ALMMGEF_Target_Effect_Risen')
    r.set('VMAD', struct.pack('<hhH', 6, 2, 1) + wstr('A1ALMMGEF_RisenEffect') + b'\0' + struct.pack('<H', 3) +
          wstr('AllyFaction') + obj(PLAYER_FACTION) + wstr('Aggression') + obj(AGGRESSION) +
          wstr('ActorTypes') + objs(ACTOR_TYPES))
    r.mark_dirty()
    p.save(data / MAIN)
    print("Necromancer's risen hunt enemies")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    path = HERE / 'fix_testing2_21.txt'
    path.write_text('# Generated by fix_testing2_21.py - edit that, not this file.\n' + '\n'.join(EDITS) + '\n', encoding='utf8')
    r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout', '900',
                        '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
    result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
    print(result.splitlines()[0])
    if ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit('\n'.join(l for l in result.splitlines() if l.startswith('ERROR')) + r.stderr)
    write_raw(data, ack)


if __name__ == '__main__':
    main()
