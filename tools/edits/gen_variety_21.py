def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    sys.path.insert(0, str(HERE.parent / 'config'))
    from ack.plugin import Plugin
    from ack.plugin.records import Subrecord
    from settings import on_conds

    p = Plugin.load(data / MAIN)
    fid = lambda e: e if isinstance(e, int) else p.by_edid(e).formid

    def ctda(fn, op, value, param=0, flags=0, run_on=0, ref=0) -> Subrecord:
        return Subrecord('CTDA', struct.pack('<B3sfH2sIIIIi', (op << 5) | flags, b'\0\0\0', value, fn, b'\0\0',
                                             fid(param), 0, run_on, ref, -1))

    def set_conditions(r, per_effect):
        out, n = [], -1
        for s in r.subrecords:
            if s.sig == 'CTDA':
                continue
            out.append(s)
            n += s.sig == 'EFID'
            if s.sig == 'EFIT':
                out += [ctda(*c) for c in per_effect[n]]
        r.subrecords[:] = out

    def entry_blocks(perk):
        subs = perk.subrecords
        i = next(k for k, s in enumerate(subs) if s.sig == 'PRKE')
        head, blocks, cur = subs[:i], [], []
        for s in subs[i:]:
            cur.append(s)
            if s.sig == 'PRKF':
                blocks.append(cur)
                cur = []
        return head, blocks

    def set_blocks(perk, blocks):
        head, _ = entry_blocks(perk)
        out = list(head)
        for n, block in enumerate(blocks):
            for s in block:
                if s.sig == 'EPFB':
                    s = Subrecord('EPFB', struct.pack('<H', n))
                elif s.sig == 'PRKE':
                    s = Subrecord('PRKE', struct.pack('<BBB', 2, 0, 100))    # applied after the vanilla perks' entries
                out.append(s)
        perk.subrecords[:] = out

    def entries(r, ents):
        blocks = []
        for (ep, tabs), fn, value, conds in ents:
            b = [Subrecord('PRKE', b''), Subrecord('DATA', struct.pack('<BBB', ep, fn, tabs))]
            for tab, cs in sorted(conds.items()):
                b += [Subrecord('PRKC', bytes([tab]))] + [ctda(*c) for c in cs]
            if isinstance(value, float):
                b += [Subrecord('EPFT', b'\x01'), Subrecord('EPFB', b''), Subrecord('EPFD', struct.pack('<f', value))]
            else:                                                  # ('lvli', form ID)
                b += [Subrecord('EPFT', b'\x03'), Subrecord('EPFB', b''), Subrecord('EPFD', struct.pack('<I', value[1]))]
            blocks.append(b + [Subrecord('PRKF', b'')])
        set_blocks(r, blocks)

    def wstr(s):
        return struct.pack('<H', len(s)) + s.encode('ascii')

    def vmad(script, props):
        out = struct.pack('<hhH', 6, 2, 1) + wstr(script) + b'\0' + struct.pack('<H', len(props))
        for name, kind, value in props:
            out += wstr(name)
            if kind in ('spell', 'form'):
                out += b'\x01\x01' + struct.pack('<HhI', 0, -1, fid(value))
            elif kind == 'objects':
                out += b'\x0b\x01' + struct.pack('<I', len(value)) + b''.join(struct.pack('<HhI', 0, -1, v) for v in value)
            elif kind == 'float':
                out += b'\x04\x01' + struct.pack('<f', value)
        return out

    def gate_blocks(temp, rank1, rank2):
        """The vanilla rank 1 'Set Player Gate' entry, three times: one level above each rank the player has."""
        block = next(b for b in entry_blocks(p.by_edid(temp))[1]
                     if any(s.sig == 'DATA' and s.data[1] == SET for s in b))
        data = next(s for s in block if s.sig == 'DATA')
        out = []
        for level, conds in ((1.0, [(HAS_PERK, EQ, 0.0, rank1)]),
                             (2.0, [(HAS_PERK, EQ, 1.0, rank1), (HAS_PERK, EQ, 0.0, rank2)]),
                             (3.0, [(HAS_PERK, EQ, 1.0, rank2)])):
            out.append([Subrecord('PRKE', b''), data, Subrecord('PRKC', b'\x00'), *[ctda(*c) for c in conds],
                        Subrecord('EPFT', b'\x01'), Subrecord('EPFB', b''), Subrecord('EPFD', struct.pack('<f', level)),
                        Subrecord('PRKF', b'')])
        return out

    for kind, edid, arg in RAW:
        r = p.by_edid(edid)
        assert r is not None, edid
        if kind == 'conditions':
            set_conditions(r, arg)
        elif kind == 'strip':
            r.subrecords[:] = [s for s in r.subrecords if s.sig != 'CTDA']
        elif kind == 'entries':
            entries(r, arg)
        elif kind == 'vmad':
            r.set('VMAD', vmad(*arg))
        elif kind == 'vmad_swap':
            v = r.get('VMAD').data
            old, new = struct.pack('<I', fid(arg[0])), struct.pack('<I', fid(arg[1]))
            assert v.count(old) == 1, edid
            r.set('VMAD', v.replace(old, new))
        elif kind == 'plain':                    # no poison keyword, resistance, shader or immunity condition
            d = bytearray(r.get('DATA').data)
            assert struct.unpack_from('<I', d, 16)[0] == POISON_RESIST, edid           # the layout this assumes
            assert struct.unpack_from('<I', d, 32)[0] == POISON_SHADER, edid
            struct.pack_into('<I', d, 16, 0)     # resist value
            struct.pack_into('<I', d, 32, 0)     # hit shader
            r.set('DATA', bytes(d))
            r.subrecords[:] = [s for s in r.subrecords if s.sig not in ('CTDA', 'KSIZ', 'KWDA')]
        elif kind == 'flags':                    # clear these DATA flags
            d = bytearray(r.get('DATA').data)
            struct.pack_into('<I', d, 0, struct.unpack_from('<I', d, 0)[0] & ~arg)
            r.set('DATA', bytes(d))
        elif kind == 'medic':                    # Medic rank 1's entries, x1.3 for anyone, not +n for rank 1 only
            blocks = []
            for b in entry_blocks(p.by_edid(arg))[1]:
                out = []
                for s in b:
                    if s.sig == 'CTDA' and struct.unpack_from('<H', s.data, 8)[0] == HAS_PERK:
                        continue
                    if s.sig == 'DATA':
                        s = Subrecord('DATA', bytes([s.data[0], MUL, s.data[2]]))
                    elif s.sig == 'EPFD':
                        s = Subrecord('EPFD', struct.pack('<f', 1.3))
                    out.append(s)
                blocks.append(out)
            set_blocks(r, blocks)
        elif kind == 'gates':
            set_blocks(r, gate_blocks(arg[0], LOCKSMITH1, LOCKSMITH2) + gate_blocks(arg[1], HACKER1, HACKER2))
        r.mark_dirty()

    # OP flag on or off, whatever the template had
    item, glob = fid('A1ALMSET_ShowOP'), fid('A1ALMSETG_ShowOP')
    want = {fid(OM + n): n in OP for n in NEW}
    for c in p.records('COBJ'):
        cn = c.get('CNAM')
        if not cn or c.edid.endswith('_Unlocked') or struct.unpack('<I', cn.data)[0] not in want:
            continue
        subs = [s for s in c.subrecords if not (s.sig == 'CTDA' and struct.unpack_from('<HxxI', s.data, 8) in (
            (47, item), (74, glob)))]
        if want[struct.unpack('<I', cn.data)[0]]:
            last = max(i for i, s in enumerate(subs) if s.sig == 'CTDA')
            subs[last + 1:last + 1] = [Subrecord('CTDA', d) for d in on_conds(item, glob)]
        c.subrecords[:] = subs
        c.mark_dirty()
    p.save(data / MAIN)
    print(f'{len(NEW)} legendaries: {len(OP)} OP, {len(NEW) - len(OP)} balanced')


def apply(ack: Path, path: Path) -> None:
    r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout', '900',
                        '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
    result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
    print(result.splitlines()[0])
    if ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit('\n'.join(l for l in result.splitlines() if l.startswith('ERROR')) + r.stderr)


