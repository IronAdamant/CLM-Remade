"""Disintegratin' in every CLM laser colour (author's request, 2026-10-12).

    python tools/edits/disintegratin_colours.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

Run after tools/assets/disintegration_colors.py (the coloured crit spells, glow shaders and ash piles). Each new
variant is a copy of Disintegratin' (Green) - legendary, enchantment, its hit effect, costly and free recipes (with
their setting and picker conditions) - pointed at its colour's records. Then re-run the loot tools (families.py,
plan.py, generate.py) and tools/config/picker.py so the variants get loose mods, unlocked recipes and their picks.
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
COLOURS = {'Purple': 'Purple', 'Gold': 'Gold', 'Orange': 'Orange', 'Pink': 'Pink', 'DeepBlue': 'Deep Blue'}
OMOD = 'A1ALMOMOD_Legendary_Weapon_Contact_Disintegration_Variant_{}'
ENCH = 'A1ALMEnch_FaF_Contact_Custom_Effect_Disintegration_{}'
MGEF = 'A1ALMMGEF_Target_Effect_Hostile_Disintegration_{}'
SPEL = 'A1ALMSPEL_CritLaser{}'
EFSH, ACTI = 'A1ALMEFSH_CritLaser{}', 'A1ALMACTI_AshPile{}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'

    s = ['# Generated by tools/edits/disintegratin_colours.py', f'file | {MAIN}']
    for c, name in COLOURS.items():
        s += [f'copy | @{MGEF.format("Green")} | {MGEF.format(c)}',
              f'set | {MGEF.format(c)} | FULL | CLM: Targeted Disintegration [{name}]',
              f'prop | {MGEF.format(c)} | AttachAshPile | MagicEffectShader | Object | @{EFSH.format(c)}',
              f'prop | {MGEF.format(c)} | AttachAshPile | AshPileObject | Object | @{ACTI.format(c)}',
              f'copy | @{ENCH.format("Green")} | {ENCH.format(c)}',
              f'set | {ENCH.format(c)} | FULL | CLM: Disintegration ({name})',
              f'copy | @{OMOD.format("Green")} | {OMOD.format(c)}',
              f"set | {OMOD.format(c)} | FULL | CLM: Disintegratin' ({name})",
              f'copy | @co_{OMOD.format("Green")} | co_{OMOD.format(c)}',
              f'copy | @co_{OMOD.format("Green")}FREE | co_{OMOD.format(c)}FREE']
    spec = HERE / 'disintegratin_colours.spec'
    spec.write_text('\n'.join(s) + '\n', encoding='utf8')
    subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'build', MAIN, '--save', '--timeout', '600',
                    '--param', f'SPEC={spec}'], cwd=ack, capture_output=True, text=True)
    result = (sorted((ack / 'private' / 'runs').glob('*-build'))[-1] / 'result.txt').read_text(encoding='utf8')
    print(result.splitlines()[0])
    if ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit('\n'.join(l for l in result.splitlines() if 'ERR' in l))

    # the copies still point at Green's records: re-point them at their colour's
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin
    p = Plugin.load(data / MAIN)
    fid = lambda e: struct.pack('<I', p.by_edid(e).formid)

    def swap(edid: str, pairs: list[tuple[str, str]]) -> None:
        r = p.by_edid(edid)
        for old, new in pairs:
            n = 0
            for sub in r.subrecords:
                if sub.sig == 'LNAM' and r.sig == 'OMOD':
                    continue        # Green's loose mod: tools/loot/generate.py gives each variant its own
                if fid(old) in sub.data:
                    sub.data = sub.data.replace(fid(old), fid(new))
                    n += 1
            assert n, (edid, old)
        r.mark_dirty()

    for c in COLOURS:
        swap(ENCH.format(c), [(MGEF.format('Green'), MGEF.format(c))])
        swap(OMOD.format(c), [(ENCH.format('Green'), ENCH.format(c)), (SPEL.format('Green'), SPEL.format(c))])
        for suffix in ('', 'FREE'):
            swap(f'co_{OMOD.format(c)}{suffix}', [(OMOD.format('Green'), OMOD.format(c))])
    p.save(data / MAIN)
    print(f"{len(COLOURS)} Disintegratin' variants: {', '.join(COLOURS.values())}")


if __name__ == '__main__':
    main()
