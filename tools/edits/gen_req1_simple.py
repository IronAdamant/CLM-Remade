"""Generate tools/edits/req1_simple_legendaries.txt: 2.1's first requests from the 2016-17 log (docs/PLAN_2.1.md 1),
the ones that are plain stats. Each is a copy of its closest sibling (legendary and recipes, so it keeps the mod's
naming, config categories and OP flag), with only the part that differs changed.

    python tools/edits/gen_req1_simple.py

- Jumpy (10%) and (25%) (Doom1993: "if you can get the jumping ability to like 10%"; the 1.09 author promised it).
- ViscousVitriol's "fairly simple" effects without the extra stuff or long descriptions: Rapid Fire (100%) (fire
  rate only), Rapid Hurtin' (10x damage and 2x fire rate together) and Crippling (100%). His "10x damage" alone is
  Hurtin' (1000%), added in 2.0.
"""
from pathlib import Path

OM = 'A1ALMOMOD_Legendary_'
CO = 'co_A1ALMOMOD_Legendary_'
PROP1 = 'DATA\\Properties\\[0]\\Value 1'
DAMAGE_TYPES = ('dtCryo', 'dtElectrical', 'dtEnergy', 'dtFire', 'dtPhysical', 'dtPoison', 'dtRadiationExposure',
                'dtRadiationIngestion')
lines = ['# Generated by gen_req1_simple.py - edit that, not this file.']


def legendary(new, template, recipes, name, desc):
    """Copy a legendary and both its recipes (costly + FREE), point the recipes at the copy, set name and text."""
    lines.extend([
        f'rec.copy | {OM}{template} | {OM}{new}',
        f'text.set | {OM}{new} | FULL | {name}',
        f'text.set | {OM}{new} | DESC | {desc}',
        f'rec.copy | {CO}{recipes} | {CO}{new}',
        f'rec.copy | {CO}{recipes}FREE | {CO}{new}FREE',
        f'field.set | {CO}{new} | CNAM | @{OM}{new}',
        f'field.set | {CO}{new}FREE | CNAM | @{OM}{new}',
    ])


# --- Jumpy (10%), (25%): below the 50% the family starts at ---
for pct in (10, 25):
    ench = f'A1ALMEnch_Fortify_Effect_JumpHeightMult_{pct}'
    lines += [f'rec.copy | A1ALMEnch_Fortify_Effect_JumpHeightMult_50 | {ench}',
              f'text.set | {ench} | FULL | CLM: Fortify Effect [{pct}% Jump Height Boost]',
              f'field.set | {ench} | Effects\\[0]\\EFIT\\Magnitude | {1 + pct / 100}']
    new = f'Armor_PerkV_Fortify_Jumpy_{pct}'
    legendary(new, 'Armor_PerkV_Fortify_Jumpy_50', 'Armor_PerkV_Fortify_Jumpy_50', f'CLM: Jumpy ({pct}%)',
              f'This mod increases your Jump Height by {pct}%')
    lines.append(f'field.set | {OM}{new} | {PROP1} | @{ench}')

# --- Rapid Fire (100%): Quicker (100%) without the reload part ---
legendary('Weapon_RapidFire_100P', 'Weapon_Quicker_Variant_100P', 'Weapon_Quicker_Variant_100P',
          'CLM: Rapid Fire (100%)', 'Your weapon fires twice as fast. Nothing else.')
lines.append(f'prop.remove | {OM}Weapon_RapidFire_100P | ReloadSpeed')

# --- Rapid Hurtin': ten times the damage (x1 + 9) and twice the fire rate; OP like Hurtin' (1000%) ---
legendary('Weapon_DamageBoost_Rapid', 'Weapon_DamageBoost_10x', 'Weapon_DamageBoost_10x', "CLM: Rapid Hurtin'",
          'Ten times the damage, twice the fire rate. Nothing else.')
lines.append(f'prop.set | {OM}Weapon_DamageBoost_Rapid | AttackDamage | MUL+ADD | 9')
lines += [f'prop.set | {OM}Weapon_DamageBoost_Rapid | DamageTypeValues[{dt}] | MUL+ADD | 9' for dt in DAMAGE_TYPES]
lines.append(f'prop.add | {OM}Weapon_DamageBoost_Rapid | Speed | MUL+ADD | 1 | {OM}Weapon_Quicker_Base')

# --- Crippling (100%): Crippingly Rapid's recipe, the 100% cripple enchantment alone ---
legendary('Weapon_Crippling_100P', 'Weapon_Chilling', 'Weapon_Crippingly_Rapid', 'CLM: Crippling (100%)',
          'Every hit cripples the limb it hits. Nothing else.')
lines.append(f'field.set | {OM}Weapon_Crippling_100P | {PROP1} | @A1ALMEnch_FaF_Contact_Custom_Effect_Cripple_100P')

out = Path(__file__).with_name('req1_simple_legendaries.txt')
out.write_text('\n'.join(lines) + '\n', encoding='utf8')
print(f'{out.name}: {len(lines) - 1} edits')
