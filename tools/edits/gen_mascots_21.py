"""2.1: "mascot" legendaries for the concise view (docs/CONCISE_VIEW_PLAN.md; author's decision 2026-10-14): one
balanced legendary that stands for a whole group of similar effects, where no single member did.

    python tools/edits/gen_mascots_21.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

Each copies its group's clearest member (legendary, recipes and effect records) and changes what differs. A mascot
that triggers on several conditions is on more often than a member that needs one, so its numbers are lower.
Records only, except Untouchable (Elements), which uses the Untouchable family's script (PC and Xbox).
Run tools/config/concise.py afterwards (the groups name these as their shown legendary).
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
OM = 'A1ALMOMOD_Legendary_'
CO = 'co_A1ALMOMOD_Legendary_'
PROP = 'DATA\\Properties\\[{}]\\Value 1'
HEALTH_PCT, IS_SNEAKING, WORN_HAS_KEYWORD = 430, 286, 682
EQ, GE, LT = 0, 3, 4
WEAPON_DAMAGE, MUL = (35, 3), 3
RESISTANCES = ('Acid', 'Electric', 'Explosion', 'LimbDamage', 'Poison', 'Radiation')
NEW = []
RAW = []
lines = ['# Generated by gen_mascots_21.py - edit that, not this file.']


def legendary(new, template, name, desc, recipes=None):
    NEW.append(new)
    recipes = recipes or template
    lines.extend([f'rec.copy | {OM}{template} | {OM}{new}', f'text.set | {OM}{new} | FULL | {name}',
                  f'text.set | {OM}{new} | DESC | {desc}', f'rec.copy | {CO}{recipes} | {CO}{new}',
                  f'rec.copy | {CO}{recipes}FREE | {CO}{new}FREE', f'field.set | {CO}{new} | CNAM | @{OM}{new}',
                  f'field.set | {CO}{new}FREE | CNAM | @{OM}{new}'])


def edits() -> list[str]:
    global lines
    # Opportunist's (Situational damage): +40% on a sneak attack, a full-health target or below half health; once
    kw, e = 'A1ALMKW_WeaponPerk_Weapon_Opportunists', 'A1ALMEnch_Constant_Effect_Custom_Effect_Opportunists'
    m, p = 'A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_Opportunists', 'A1ALMPERK_Legendary_Hidden_Weapon_Opportunists'
    lines.extend([f'rec.copy | A1ALMKW_WeaponPerk_Weapon_Bloodlust | {kw}',
                  f'rec.copy | A1ALMPERK_Legendary_Hidden_Weapon_Bloodlust | {p}', f"text.set | {p} | FULL | CLM Perk: Opportunist's",
                  f'rec.copy | A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_Bloodlust | {m}',
                  f"text.set | {m} | FULL | CLM Perk: Opportunist's",
                  f'field.set | {m} | Magic Effect Data\\DATA\\Perk to Apply | @{p}',
                  f'rec.copy | A1ALMEnch_Constant_Effect_Custom_Effect_Bloodlust | {e}', f"text.set | {e} | FULL | CLM: Opportunist's",
                  f'field.set | {e} | Effects\\[0]\\EFID | @{m}'])
    legendary('Weapon_Opportunists', 'Weapon_Bloodlust', "CLM: Opportunist's",
              '+40% damage on a sneak attack, against a target at full health, or while you are below half health. '
              'Only one of them counts at a time.')
    lines += [f'field.set | {OM}Weapon_Opportunists | {PROP.format(0)} | @{kw}',
              f'field.set | {OM}Weapon_Opportunists | {PROP.format(1)} | @{e}']
    RAW.append(('opportunists', p, kw))

    # Resistance (All) (Resistances): 25% less from each of the six damage types the single ones halve
    e, m, p = ('A1ALMEnch_Constant_Effect_Custom_Effect_Resistance_All',
               'A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_Resistance_All', 'A1ALMPERK_Legendary_Hidden_Armor_Resistance_All')
    lines.extend([f'rec.copy | A1ALMPERK_Legendary_Hidden_Armor_Resistance_Acid | {p}', f'text.set | {p} | FULL | CLM Perk: Resistance (All)',
                  f'rec.copy | A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_Resistance_Acid | {m}',
                  f'text.set | {m} | FULL | CLM Perk: Resistance (All)',
                  f'field.set | {m} | Magic Effect Data\\DATA\\Perk to Apply | @{p}',
                  f'rec.copy | A1ALMEnch_Constant_Effect_Custom_Effect_Resistance_Acid | {e}', f'text.set | {e} | FULL | CLM: Resistance (All)',
                  f'field.set | {e} | Effects\\[0]\\EFID | @{m}'])
    legendary('Armor_Resistance_All', 'Armor_Resistance_Acid', 'CLM: Resistance (All)',
              'You take 25% less acid, electrical, explosion, poison and radiation damage, and your limbs take 25% less '
              'damage.')
    lines.append(f'field.set | {OM}Armor_Resistance_All | {PROP.format(0)} | @{e}')
    RAW.append(('resist_all', p, None))

    # Untouchable (Elements) (Melee reactions): 20% each to freeze, burn or shock a melee attacker
    e = 'A1ALMEnch_Constant_Effect_Untouchable_Elements'
    lines.extend([f'rec.copy | A1ALMEnch_Constant_Effect_Untouchable_Freeze | {e}', f'text.set | {e} | FULL | CLM: Untouchable (Elements)'])
    for i, src in enumerate(('CryoFreeze', 'Fire', 'Electrified')):
        m = f'A1ALMMGEF_Constant_Effect_OnMeleeHits_{src}_20P'
        lines.extend([f'rec.copy | A1ALMMGEF_Constant_Effect_OnMeleeHits_{src} | {m}'])
        lines.append(f'field.set | {e} | Effects\\[0]\\EFID | @{m}' if i == 0 else f'effect.add | {e} | 0 | @{m}')
        RAW.append(('chance', m, 0.2))
    legendary('Armor_PerkV_Untouchable_Elements', 'Armor_PerkV_Untouchable_Freeze', 'CLM: Untouchable (Elements)',
              'When hostiles attack you in melee, they have a 20% chance each to be frozen, set on fire and shocked.')
    lines.append(f'field.set | {OM}Armor_PerkV_Untouchable_Elements | {PROP.format(0)} | @{e}')

    # Radiatin' (Elements) (Damaging auras): a little of each aura
    sp, cl, e = ('A1ALMSPEL_Aura_Radiating_Elements', 'A1ALMMGEF_Cloak_Radiating_Elements',
                 'A1ALMEnch_Constant_Effect_Custom_Effect_Radiating_Elements')
    lines.extend([f'rec.copy | A1ALMSPEL_Aura_Radiating_Fire | {sp}', f"text.set | {sp} | FULL | CLM: Radiatin' (Elements)",
                  f'effect.magnitude | {sp} | 0 | 2'])
    for i, (aura, mag) in enumerate((('Shock', 2), ('Rads', 3), ('Slow', 15)), start=1):
        lines += [f'effect.add | {sp} | 0 | @A1ALMMGEF_Aura_{aura}', f'effect.magnitude | {sp} | {i} | {mag}']
    lines.extend([f'rec.copy | A1ALMMGEF_Cloak_Radiating_Fire | {cl}', f"text.set | {cl} | FULL | CLM: Radiatin' (Elements)",
                  f'field.set | {cl} | Magic Effect Data\\DATA\\Assoc. Item | @{sp}',
                  f'rec.copy | A1ALMEnch_Constant_Effect_Custom_Effect_Radiating_Fire | {e}',
                  f"text.set | {e} | FULL | CLM: Radiatin' (Elements)", f'field.set | {e} | Effects\\[0]\\EFID | @{cl}'])
    legendary('Armor_Radiating_Elements', 'Armor_Radiating_Fire', "CLM: Radiatin' (Elements)",
              'Enemies near you burn, are shocked (2 damage a second each) and irradiated (3 rads a second), and move '
              '15% slower.')
    lines.append(f'field.set | {OM}Armor_Radiating_Elements | {PROP.format(0)} | @{e}')

    # Double Tappin' (Extra projectiles): the base game's Two Shot
    legendary('Weapon_DoubleTapping', 'Weapon_ShotgunSurgeons_Trainee', "CLM: Double Tappin'",
              "Your weapon fires one more projectile, each at full damage, with a 30% wider spread (like the base game's "
              'Two Shot).')
    lines += [f'prop.set | {OM}Weapon_DoubleTapping | NumProjectiles | ADD | 1',
              f'prop.add | {OM}Weapon_DoubleTapping | AttackDamage | MUL+ADD | 1 | {OM}Weapon_DamageBoost_1x']

    # Vitality (Healing): steady healing, faster when you are close to death
    e = 'A1ALMEnch_Constant_Effect_Custom_Effect_Vitality'
    lines.extend([f'rec.copy | A1ALMEnch_Constant_Effect_Custom_Effect_Regenerative_Slow | {e}', f'text.set | {e} | FULL | CLM: Vitality',
                  f'effect.magnitude | {e} | 0 | 1', f'effect.magnitude | {e} | 1 | 2'])
    RAW.append(('conditions', e, [[], [(HEALTH_PCT, LT, 0.25, 0)]]))
    legendary('Armour_Vitality', 'Armour_Regenerative_Slow', 'CLM: Vitality',
              'You heal 1 health per second, and 3 per second while your health is below 25%.')
    lines.append(f'field.set | {OM}Armour_Vitality | {PROP.format(0)} | @{e}')

    # Elemental Strikin' (Elemental hits): Nature's Wrath without its fire rate
    legendary('Weapon_ElementalStriking', 'Weapon_NaturesWrath', "CLM: Elemental Strikin'",
              'Each hit has a 10% chance each to deal 20 fire, cryo, poison and electrical damage over two seconds.')
    lines.append(f'prop.remove | {OM}Weapon_ElementalStriking | Speed')
    return lines


def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    sys.path.insert(0, str(HERE.parent / 'config'))
    from ack.plugin import Plugin
    from ack.plugin.records import Subrecord
    from settings import on_conds

    p = Plugin.load(data / MAIN)
    fid = lambda e: p.by_edid(e).formid

    def ctda(fn, op, value, param=0):
        return Subrecord('CTDA', struct.pack('<B3sfH2sIIIIi', op << 5, b'\0\0\0', value, fn, b'\0\0', param, 0, 0, 0, -1))

    def entry_blocks(perk):
        subs = perk.subrecords
        i = next(k for k, s in enumerate(subs) if s.sig == 'PRKE')
        head, blocks, cur = subs[:i], [], []
        for s in subs[i:]:
            cur.append(s)
            if s.sig == 'PRKF':
                blocks.append(cur)
                cur = []
        return head, blocks

    for kind, edid, arg in RAW:
        r = p.by_edid(edid)
        if kind == 'opportunists':
            kw = ctda(WORN_HAS_KEYWORD, EQ, 1.0, fid(arg))
            ways = [([kw, ctda(HEALTH_PCT, LT, 0.5)], []),                                  # low health
                    ([kw, ctda(HEALTH_PCT, GE, 0.5)], [ctda(HEALTH_PCT, EQ, 1.0)]),         # full-health target
                    ([kw, ctda(HEALTH_PCT, GE, 0.5), ctda(IS_SNEAKING, EQ, 1.0)], [ctda(HEALTH_PCT, LT, 1.0)])]  # sneak
            subs = r.subrecords
            del subs[next(i for i, s in enumerate(subs) if s.sig == 'PRKE'):]
            for n, (owner, target) in enumerate(ways):      # the three never hold together: one +40% at most
                subs += [Subrecord('PRKE', struct.pack('<BBB', 2, 0, 50)),
                         Subrecord('DATA', struct.pack('<BBB', WEAPON_DAMAGE[0], MUL, WEAPON_DAMAGE[1])),
                         Subrecord('PRKC', b'\0'), *owner] + ([Subrecord('PRKC', b'\x02'), *target] if target else []) + \
                        [Subrecord('EPFT', b'\x01'), Subrecord('EPFB', struct.pack('<H', n)),
                         Subrecord('EPFD', struct.pack('<f', 1.4)), Subrecord('PRKF', b'')]
        elif kind == 'resist_all':
            head, out = entry_blocks(r)[0], []
            for k in RESISTANCES:
                out += entry_blocks(p.by_edid(f'A1ALMPERK_Legendary_Hidden_Armor_Resistance_{k}'))[1]
            subs = list(head)
            for n, block in enumerate(out):
                for s in block:
                    if s.sig == 'EPFB':
                        s = Subrecord('EPFB', struct.pack('<H', n))
                    elif s.sig == 'EPFD' and len(s.data) == 4 and round(struct.unpack('<f', s.data)[0], 3) == 0.5:
                        s = Subrecord('EPFD', struct.pack('<f', 0.75))
                    subs.append(s)
            r.subrecords[:] = subs
        elif kind == 'chance':                             # A1ALMMGEF_OnMeleeEffect's ChanceToCast (1.0 = always)
            v = bytearray(r.get('VMAD').data)
            name = b'ChanceToCast'
            at = v.index(struct.pack('<H', len(name)) + name) + 2 + len(name)
            assert v[at] == 4, edid                        # a float property
            struct.pack_into('<f', v, at + 2, arg)
            r.set('VMAD', bytes(v))
        elif kind == 'conditions':
            out, n = [], -1
            for s in r.subrecords:
                if s.sig == 'CTDA':
                    continue
                out.append(s)
                n += s.sig == 'EFID'
                if s.sig == 'EFIT':
                    out += [ctda(*c) for c in arg[n]]
            r.subrecords[:] = out
        r.mark_dirty()

    item, glob = fid('A1ALMSET_ShowOP'), fid('A1ALMSETG_ShowOP')       # all balanced, whatever the template was
    want = {fid(OM + n) for n in NEW}
    for c in p.records('COBJ'):
        cn = c.get('CNAM')
        if cn and not c.edid.endswith('_Unlocked') and struct.unpack('<I', cn.data)[0] in want:
            c.subrecords[:] = [s for s in c.subrecords if not (s.sig == 'CTDA' and struct.unpack_from('<HxxI', s.data, 8)
                                                                 in ((47, item), (74, glob)))]
            c.mark_dirty()
    p.save(data / MAIN)
    print(f'{len(NEW)} mascots written')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    ap.add_argument('--raw-only', action='store_true')
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    path = HERE / 'mascots_21.txt'
    path.write_text('\n'.join(edits()) + '\n', encoding='utf8')
    if not a.raw_only:
        r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout', '900',
                            '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
        result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
        print(result.splitlines()[0])
        if ' 0 errors' not in result.splitlines()[0]:
            raise SystemExit('\n'.join(l for l in result.splitlines() if l.startswith('ERROR')) + r.stderr)
    write_raw(data, ack)


if __name__ == '__main__':
    main()
