"""2.1: fifth round of fixes from the author's in-game testing and video (2026-10-16).

    python tools/edits/fix_testing5_21.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

- Jumper's (and Momentum, built the same way): the timed spell they cast on the wearer never changed jump height (the
  debug recorder showed JumpHeightMult unchanged while the script cast it). They now add an ability with the same
  constant effects Jumpy and Speedy use, and remove it after AbilitySeconds (A1ALMMGEF_OnHit/OnKillArmourEffect).
- DragonBlade (script only): SetPosition instead of MoveTo, which put up a loading screen on every dash.
- Cinematic Excellence: the CE Test is over: back to 1 kill in 10 and its normal name.
- CQC: the extra rounds were the gun's plain projectile (Weapon.Fire); the burst now makes the shooter fire the gun
  itself with ActionFireSingle (Actor.PlayIdleAction), so they are the real modded shot, falling back to the plain one
  if the game refuses the action (A1ALMMGEF_BurstFireEffect's FireAction).
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
HEALTH = 0x2D4
ACTION_FIRE_SINGLE = 0x4A5A    # Fallout4.esm AACT ActionFireSingle
JUMP, RUSH = 'A1ALMSPEL_Ability_Armor_Jumpers_Boost', 'A1ALMSPEL_Ability_Armor_Momentum_Rush'
EDITS = [
    f'rec.copy | A1ALMSPEL_Ability_Armor_Jumpers | {JUMP}', f"text.set | {JUMP} | FULL | CLM: Jumper's (jump)",
    f'field.set | {JUMP} | Effects\\[0]\\EFID | @A1ALMMGEF_Fortify_Effect_Movement_Jump_Height_Mult',
    f'effect.magnitude | {JUMP} | 0 | 4',
    f'rec.copy | A1ALMSPEL_Ability_Armor_Momentum | {RUSH}', f'text.set | {RUSH} | FULL | CLM: Momentum (rush)',
    f'field.set | {RUSH} | Effects\\[0]\\EFID | @A1ALMMGEF_Fortify_Effect_Movement_Speed_Mult',
    f'effect.magnitude | {RUSH} | 0 | 20',
    f'effect.add | {RUSH} | 0 | @A1ALMMGEF_Fortify_Effect_Action_Point_Regen',
    f'effect.magnitude | {RUSH} | 1 | 25',
    'text.set | A1ALMOMOD_Legendary_Weapon_CinematicExcellence | FULL | CLM: Cinematic Excellence',
    "text.set | A1ALMOMOD_Legendary_Weapon_CQC | DESC | Every shot becomes a three-round burst: your gun fires twice "
    'more on its own, with its mods and your ammo. (PC and Xbox.)',
]


def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin

    p = Plugin.load(data / MAIN)
    fid = lambda e: p.by_edid(e).formid
    w = lambda s: struct.pack('<H', len(s)) + s.encode('ascii')
    obj = lambda f: b'\x01\x01' + struct.pack('<HhI', 0, -1, f)
    flt = lambda v: b'\x04\x01' + struct.pack('<f', v)
    bln = lambda v: b'\x05\x01' + bytes([1 if v else 0])

    def vmad(script, props):
        return struct.pack('<hhH', 6, 2, 1) + w(script) + b'\0' + struct.pack('<H', len(props)) + \
            b''.join(w(n) + v for n, v in props)

    r = p.by_edid('A1ALMMGEF_Constant_Effect_Armor_Jumpers')
    r.set('VMAD', vmad('A1ALMMGEF_OnHitArmourEffect', [('Health', obj(HEALTH)), ('SelfAbility', obj(fid(JUMP))),
                                                      ('OnlyOwnAttacks', bln(True)), ('Cooldown', flt(1.0)),
                                                      ('AbilitySeconds', flt(3.0))]))
    r.mark_dirty()
    r = p.by_edid('A1ALMMGEF_Constant_Effect_Armor_Momentum')
    r.set('VMAD', vmad('A1ALMMGEF_OnKillArmourEffect', [('Health', obj(HEALTH)), ('SelfAbility', obj(fid(RUSH))),
                                                       ('AbilitySeconds', flt(10.0))]))
    r.mark_dirty()
    r = p.by_edid('A1ALMMGEF_Constant_Effect_Weapon_CQC')                    # the burst fires the real shot
    r.set('VMAD', vmad('A1ALMMGEF_BurstFireEffect', [('FireAction', obj(ACTION_FIRE_SINGLE))]))
    r.mark_dirty()
    r = p.by_edid('A1ALMMGEF_Constant_Effect_Weapon_CinematicExcellence')      # CE Test over: 1 kill in 10
    v = bytearray(r.get('VMAD').data)
    name = b'ChanceToCast'
    at = v.index(struct.pack('<H', len(name)) + name) + 2 + len(name)
    struct.pack_into('<f', v, at + 2, 0.1)
    r.set('VMAD', bytes(v))
    r.mark_dirty()
    p.save(data / MAIN)
    print("Jumper's and Momentum use abilities; Cinematic Excellence back to 1 in 10")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    path = HERE / 'fix_testing5_21.txt'
    path.write_text('# Generated by fix_testing5_21.py - edit that, not this file.\n' + '\n'.join(EDITS) + '\n', encoding='utf8')
    r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout', '900',
                        '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
    result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
    print(result.splitlines()[0])
    if ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit('\n'.join(l for l in result.splitlines() if l.startswith('ERROR')) + r.stderr)
    write_raw(data, ack)


if __name__ == '__main__':
    main()
