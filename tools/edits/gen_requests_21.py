def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    sys.path.insert(0, str(HERE.parent / 'config'))
    from ack.plugin import Plugin
    from ack.plugin.records import Subrecord
    from settings import on_conds

    p = Plugin.load(data / MAIN)
    fid = lambda e: p.by_edid(e).formid

    def ctda(fn, op, value, param=0, flags=0, run_on=0, ref=0) -> Subrecord:
        return Subrecord('CTDA', struct.pack('<B3sfH2sIIIIi', (op << 5) | flags, b'\0\0\0', value, fn, b'\0\0', param,
                                             0, run_on, ref, -1))

    def set_conditions(r, per_effect):
        out, n = [], -1
        for s in r.subrecords:
            if s.sig == 'CTDA':
                continue
            out.append(s)
            n += s.sig == 'EFID'
            if s.sig == 'EFIT':
                out += [ctda(*c) for c in per_effect[n]]
        r.subrecords[:] = out

    def entries(r, ents):
        subs = r.subrecords
        del subs[next(i for i, s in enumerate(subs) if s.sig == 'PRKE'):]
        for n, ((ep, tabs), fn, value, conds) in enumerate(ents):
            subs += [Subrecord('PRKE', struct.pack('<BBB', 2, 0, 50)), Subrecord('DATA', struct.pack('<BBB', ep, fn, tabs))]
            for tab, cs in sorted(conds.items()):
                subs += [Subrecord('PRKC', bytes([tab]))] + [ctda(*c) for c in cs]
            if isinstance(value, float):
                subs += [Subrecord('EPFT', b'\x01'), Subrecord('EPFB', struct.pack('<H', n)),
                         Subrecord('EPFD', struct.pack('<f', value))]
            else:                                                  # a spell
                subs += [Subrecord('EPFT', b'\x05'), Subrecord('EPFB', struct.pack('<H', n)),
                         Subrecord('EPFD', struct.pack('<I', value))]
            subs.append(Subrecord('PRKF', b''))

    def wstr(s):
        return struct.pack('<H', len(s)) + s.encode('ascii')

    def vmad(script, props):
        out = struct.pack('<hhH', 6, 2, 1) + wstr(script) + b'\0' + struct.pack('<H', len(props))
        for name, kind, value in props:
            out += wstr(name)
            if kind in ('spell', 'form', 'av'):
                out += b'\x01\x01' + struct.pack('<HhI', 0, -1, fid(value) if kind == 'spell' else value)
            elif kind == 'float':
                out += b'\x04\x01' + struct.pack('<f', value)
            elif kind == 'bool':
                out += b'\x05\x01' + struct.pack('<B', 1 if value else 0)
        return out

    def effects(r):
        """[(EFID, EFIT, [CTDA...]) ...] and the subrecords before the first effect."""
        subs = r.subrecords
        first = next(i for i, s in enumerate(subs) if s.sig == 'EFID')
        groups = []
        for s in subs[first:]:
            if s.sig == 'EFID':
                groups.append([s, None, []])
            elif s.sig == 'EFIT':
                groups[-1][1] = s
            elif s.sig == 'CTDA':
                groups[-1][2].append(s)
        return subs[:first], groups

    def rebuild(r, head, groups):
        r.subrecords[:] = head + [x for g in groups for x in [g[0], g[1], *g[2]]]

    for kind, edid, arg in RAW:
        r = p.by_edid(edid)
        assert r is not None, edid
        if kind in ('conditions', 'spell_conditions'):
            set_conditions(r, arg)
        elif kind == 'strip':
            r.subrecords[:] = [s for s in r.subrecords if s.sig != 'CTDA']
        elif kind == 'entries':
            entries(r, arg)
        elif kind == 'vmad':
            r.set('VMAD', vmad(arg[0], [('Health', 'av', HEALTH)] + arg[1] if arg[0] in (
                'A1ALMMGEF_OnHitArmourEffect', 'A1ALMMGEF_OnKillArmourEffect', 'A1ALMMGEF_PercentDamageEffect') else arg[1]))
        elif kind == 'vmad_swap':                       # point vanilla Fortune Finder's script at our explosion
            v = r.get('VMAD').data
            old, new = struct.pack('<I', arg[0]), struct.pack('<I', fid(arg[1]))
            assert v.count(old) == 1, edid
            r.set('VMAD', v.replace(old, new))
        elif kind == 'ability':
            ability, script_mgef = p.by_edid(arg[0]), fid(arg[1])
            subs = ability.subrecords
            first = next(i for i, s in enumerate(subs) if s.sig == 'EFID')
            ability.subrecords[:] = subs[:first] + [Subrecord('EFID', struct.pack('<I', script_mgef)),
                                                    Subrecord('EFIT', struct.pack('<fII', 0.0, 0, 0))]
            ability.mark_dirty()
            subs = r.subrecords
            del subs[next(i for i, s in enumerate(subs) if s.sig == 'PRKE'):]
            subs += [Subrecord('PRKE', struct.pack('<BBB', 1, 0, 0)), Subrecord('DATA', struct.pack('<I', ability.formid)),
                     Subrecord('PRKF', b'')]
        elif kind == 'cap_entry':                       # vanilla Fortune Finder rank 4's entry, 15% instead of 7%
            sp, mg = fid(arg[0]), fid(arg[1])
            entries(r, [((51, 3), 10, sp, {0: [(GET_RANDOM, LE, 15.0, 0)],
                                           2: [(HAS_MGEF, EQ, 0.0, mg), (GET_DEAD, EQ, 0.0, 0)]})])
        elif kind == 'brutish':
            head, groups = effects(r)
            punch = fid('A1ALMMGEF_Constant_Effect_Perk_Punching_Fire')
            on_melee = fid('A1ALMMGEF_Constant_Effect_OnMeleeHits_Fire')
            out = []
            for g in groups:
                efid = struct.unpack('<I', g[0].data)[0]
                if efid == on_melee:
                    continue                            # no more 100-point burns on melee attackers
                if efid == punch:
                    g = [Subrecord('EFID', struct.pack('<I', fid('A1ALMMGEF_Constant_Effect_Perk_Brutish_Fire'))), g[1],
                         [ctda(HEALTH_PCT, LT, 0.5)]]   # below half health, as Burning Rage
                out.append(g)
            rebuild(r, head, out)
            pk = p.by_edid('A1ALMPERK_Legendary_Hidden_Armor_Brutish_Fire')
            for i, s in enumerate(pk.subrecords):
                if s.sig == 'EPFD':
                    pk.subrecords[i] = Subrecord('EPFD', struct.pack('<I', fid(arg)))
            pk.mark_dirty()
        elif kind == 'no_damage':                       # Medic's damage cut, 50% -> 0%, on its own keyword
            for i, s in enumerate(r.subrecords):
                if s.sig == 'EPFD' and len(s.data) == 4:
                    r.subrecords[i] = Subrecord('EPFD', struct.pack('<f', 0.0))
                elif s.sig == 'CTDA' and struct.unpack_from('<H', s.data, 8)[0] == WORN_HAS_KEYWORD:
                    d = bytearray(s.data)
                    struct.pack_into('<I', d, 12, fid(arg))
                    r.subrecords[i] = Subrecord('CTDA', bytes(d))
        elif kind == 'recover':                         # a timed fortify, not a per-second increase
            d = bytearray(r.get('DATA').data)
            struct.pack_into('<I', d, 0, struct.unpack_from('<I', d, 0)[0] | 0b10)
            r.set('DATA', bytes(d))
        elif kind == 'hostile_only':
            r.subrecords[:] = [s for s in r.subrecords if s.sig != 'CTDA'] + [ctda(IS_HOSTILE, EQ, 1.0, PLAYER_REF)]
        elif kind == 'no_braking':                      # Pain Train's top rank, without power armour or the perk
            head, groups = effects(r)
            keep = groups[4:6]                          # knockback 4, damage 75
            for g in keep:
                g[2] = [c for c in g[2] if struct.unpack_from('<H', c.data, 8)[0] not in (HAS_PERK, WORN_COUNT)]
                g[2].append(ctda(IS_HOSTILE, EQ, 1.0, PLAYER_REF))
            rebuild(r, head, keep)
        r.mark_dirty()

    # OP flag on or off, whatever the template had
    item, glob = fid('A1ALMSET_ShowOP'), fid('A1ALMSETG_ShowOP')
    want = {fid(OM + n): n in OP for n in NEW}
    for c in p.records('COBJ'):
        cn = c.get('CNAM')
        if not cn or c.edid.endswith('_Unlocked') or struct.unpack('<I', cn.data)[0] not in want:
            continue
        subs = [s for s in c.subrecords if not (s.sig == 'CTDA' and struct.unpack_from('<HxxI', s.data, 8) in (
            (47, item), (74, glob)))]
        if want[struct.unpack('<I', cn.data)[0]]:
            last = max(i for i, s in enumerate(subs) if s.sig == 'CTDA')
            subs[last + 1:last + 1] = [Subrecord('CTDA', d) for d in on_conds(item, glob)]
        c.subrecords[:] = subs
        c.mark_dirty()
    p.save(data / MAIN)
    print(f'{len(NEW)} legendaries: {len(OP)} OP, {len(NEW) - len(OP)} balanced; Brutish and Advanced Titanium updated')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    ap.add_argument('--raw-only', action='store_true', help='step 2 only (step 1 already applied)')
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    path = HERE / 'requests_21.txt'
    path.write_text('\n'.join(edits()) + '\n', encoding='utf8')
    if not a.raw_only:
        r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout',
                            '900', '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
        result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
        print(result.splitlines()[0])
        if ' 0 errors' not in result.splitlines()[0]:
            raise SystemExit('\n'.join(l for l in result.splitlines() if l.startswith('ERROR')) + r.stderr)
    write_raw(data, ack)


if __name__ == '__main__':
    main()
