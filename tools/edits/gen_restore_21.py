def legendary(new, template, recipes, name, desc):
    """Copy a legendary and both its recipes, point the recipes at the copy, set name and text."""
    NEW.append(new)
    lines.extend([f'rec.copy | {OM}{template} | {OM}{new}', f'text.set | {OM}{new} | FULL | {name}',
                  f'text.set | {OM}{new} | DESC | {desc}', f'rec.copy | {CO}{recipes} | {CO}{new}',
                  f'rec.copy | {CO}{recipes}FREE | {CO}{new}FREE', f'field.set | {CO}{new} | CNAM | @{OM}{new}',
                  f'field.set | {CO}{new}FREE | CNAM | @{OM}{new}'])


def ench(new, template, name, magnitudes=None):
    lines.extend([f'rec.copy | {template} | {new}', f'text.set | {new} | FULL | {name}'])
    for i, m in enumerate(magnitudes or []):
        if m is not None:
            lines.append(f'effect.magnitude | {new} | {i} | {m}')


def perk_chain(key, ench_src, mgef_src, perk_src, name):
    """Copies of an enchantment -> perk magic effect -> hidden perk; returns the new enchantment."""
    e, m, p = f'A1ALMEnch_Constant_Effect_Custom_Effect_{key}', f'A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_{key}', \
        f'A1ALMPERK_Legendary_Hidden_Armor_{key}'
    lines.extend([f'rec.copy | {perk_src} | {p}', f'text.set | {p} | FULL | CLM Perk: {name}',
                  f'rec.copy | {mgef_src} | {m}', f'text.set | {m} | FULL | CLM Perk: {name}',
                  f'field.set | {m} | Magic Effect Data\\DATA\\Perk to Apply | @{p}'])
    ench(e, ench_src, f'CLM: {name}')
    lines.append(f'field.set | {e} | Effects\\[0]\\EFID | @{m}')
    return e, p


