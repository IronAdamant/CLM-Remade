def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    sys.path.insert(0, str(HERE.parent / 'config'))
    from ack.plugin import Plugin
    from ack.plugin.records import Subrecord
    from settings import on_conds

    p = Plugin.load(data / MAIN)

    def ctda(fn, op, value, param, flags=0) -> Subrecord:
        return Subrecord('CTDA', struct.pack('<B3sfH2sIIIIi', (op << 5) | flags, b'\0\0\0', value, fn, b'\0\0', param,
                                             0, 0, 0, -1))

    for kind, edid, arg in RAW:
        r = p.by_edid(edid)
        if kind == 'conditions':
            out, n = [], -1
            for s in r.subrecords:
                if s.sig == 'CTDA':
                    continue
                out.append(s)
                n += s.sig == 'EFID'
                if s.sig == 'EFIT':
                    out += [ctda(*c) for c in arg[n]]
            r.subrecords[:] = out
        elif kind == 'perk_values':
            for i, s in enumerate(r.subrecords):
                if s.sig == 'EPFD' and len(s.data) == 4:
                    v = round(struct.unpack('<f', s.data)[0], 4)
                    if v in arg:
                        r.subrecords[i] = Subrecord('EPFD', struct.pack('<f', arg[v]))
        elif kind == 'one_man_punching':
            subs = r.subrecords
            del subs[next(i for i, s in enumerate(subs) if s.sig == 'PRKE'):]
            melee = [ctda(FN_HAS_KEYWORD, 0, 1.0, k, 1 if i < len(MELEE_KEYWORDS) - 1 else 0)
                     for i, k in enumerate(MELEE_KEYWORDS)]
            subs += [Subrecord('PRKE', struct.pack('<BBB', 2, 0, 50)),
                     Subrecord('DATA', struct.pack('<BBB', WEAPON_DAMAGE[0], MUL, WEAPON_DAMAGE[1])),
                     Subrecord('PRKC', b'\0'), ctda(FN_WORN_HAS_KEYWORD, 0, 1.0, p.by_edid(arg).formid),
                     Subrecord('PRKC', b'\x01'), *melee,
                     Subrecord('EPFT', b'\x01'), Subrecord('EPFB', struct.pack('<H', 0)),
                     Subrecord('EPFD', struct.pack('<f', 50.0)), Subrecord('PRKF', b'')]
        r.mark_dirty()

    # OP flag: on for OP, off for everything else (some templates were OP)
    item, glob = p.by_edid('A1ALMSET_ShowOP').formid, p.by_edid('A1ALMSETG_ShowOP').formid
    want = {p.by_edid(OM + n).formid: n in OP for n in NEW}
    for c in p.records('COBJ'):
        cn = c.get('CNAM')
        if not cn or c.edid.endswith('_Unlocked') or struct.unpack('<I', cn.data)[0] not in want:
            continue
        subs = [s for s in c.subrecords if not (s.sig == 'CTDA' and struct.unpack_from('<HxxI', s.data, 8) in (
            (47, item), (74, glob)))]
        if want[struct.unpack('<I', cn.data)[0]]:
            last = max(i for i, s in enumerate(subs) if s.sig == 'CTDA')
            subs[last + 1:last + 1] = [Subrecord('CTDA', d) for d in on_conds(item, glob)]
        c.subrecords[:] = subs
        c.mark_dirty()
    p.save(data / MAIN)
    print(f'{len(NEW)} legendaries: {len(OP)} OP, {len(NEW) - len(OP)} balanced')


