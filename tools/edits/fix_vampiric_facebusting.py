"""Vampiric healing on every hit, and Face Bustin' no longer killing on every hit (Nexus complaints #6, #22).

    python tools/edits/fix_vampiric_facebusting.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

- Vampiric, Raging, Annihilating, Reaper's Embrace and Reclaimer's used the "Absorb Health" effect type, which only
  heals when the target survives the hit: kills gave nothing ("heals on mirelurks, not on molerats or radroaches").
  New script effects (A1ALMMGEF_DrainOnHitScript) heal the attacker and damage the target on every hit, one per heal
  amount (25, 50, 1 - vanilla Papyrus cannot read an effect's magnitude).
- Face Bustin' ("they'll explode after death") used vanilla's ExplodeOnContactScript, which kills the target on every
  hit. A new effect (A1ALMMGEF_ExplodeAfterDeathScript, 1 s) blows apart only targets that are dead when it ends.
  The kill-on-hit effect stays for Lucky Drawin' (1% instant kill) and Cheater's, which mean it.
Step 1 builds the new magic effects with AgentCreationKit's builder; step 2 points the enchantments at them.
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
TEMPLATE = '@A1ALMMGEF_Target_Effect_Hostile_ExplodeOnContact'   # fire-and-forget, touch, script archetype
DRAIN = {25: ['A1ALMEnch_FaF_Contact_Effect_Target_Hostile_Vampiric',
              'A1ALMEnch_FaF_Contact_Effect_Target_Hostile_Annihilating'],
         50: ['A1ALMEnch_FaF_Contact_Effect_Target_Hostile_ReapersEmbrace'],
         1: ['A1ALMEnch_FaF_Contact_Effect_Custom_Effect_Target_Hostile_Reclaimer']}
FACEBUST = 'A1ALMEnch_FaF_Contact_Effect_Target_Hostile_FaceBusting'


def spec() -> str:
    s = ['# Generated by fix_vampiric_facebusting.py', f'file | {MAIN}']
    for amount in DRAIN:
        e = f'A1ALMMGEF_Target_Effect_Hostile_DrainOnHit_{amount}'
        s += [f'copy | {TEMPLATE} | {e}', f'set | {e} | FULL | CLM: Vampiric Drain ({amount})', f'remove | {e} | VMAD',
              f'script | {e} | A1ALMMGEF_DrainOnHitScript',
              f'prop | {e} | A1ALMMGEF_DrainOnHitScript | Health | Object | @Health',
              f'prop | {e} | A1ALMMGEF_DrainOnHitScript | Amount | Float | {amount}']
    e = 'A1ALMMGEF_Target_Effect_Hostile_ExplodeAfterDeath'
    s += [f'copy | {TEMPLATE} | {e}', f'set | {e} | FULL | CLM: Explode After Death', f'remove | {e} | VMAD',
          f'script | {e} | A1ALMMGEF_ExplodeAfterDeathScript']
    return '\n'.join(s) + '\n'


def repoint(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin
    p = Plugin.load(data / MAIN)
    blood = p.by_edid('A1ALMMGEF_Target_Effect_Hostile_BloodDrain').formid
    boom = p.by_edid('A1ALMMGEF_Target_Effect_Hostile_ExplodeOnContact').formid
    for amount, enchs in DRAIN.items():
        new = p.by_edid(f'A1ALMMGEF_Target_Effect_Hostile_DrainOnHit_{amount}').formid
        for e in enchs:
            r = p.by_edid(e)
            for s in r.subrecords:
                if s.sig == 'EFID' and struct.unpack('<I', s.data)[0] == blood:
                    s.data = struct.pack('<I', new)
            r.mark_dirty()
            print(f'{e}: drain {amount} per hit')
    r = p.by_edid(FACEBUST)
    after = p.by_edid('A1ALMMGEF_Target_Effect_Hostile_ExplodeAfterDeath').formid
    swap = False
    for s in r.subrecords:
        if s.sig == 'EFID':
            swap = struct.unpack('<I', s.data)[0] == boom
            if swap:
                s.data = struct.pack('<I', after)
        elif s.sig == 'EFIT' and swap:
            mag, area, dur = struct.unpack_from('<fII', s.data)
            s.data = struct.pack('<fII', mag, area, 1) + s.data[12:]   # ends after 1 s, once the hit has landed
    r.mark_dirty()
    print(f'{FACEBUST}: explodes only after death')
    p.save(data / MAIN)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    path = HERE / 'fix_vampiric_facebusting.spec'
    path.write_text(spec(), encoding='utf8')
    r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'build', MAIN, '--save', '--timeout', '300',
                        '--param', f'SPEC={path}'], cwd=ack, capture_output=True, text=True)
    run = sorted((ack / 'private' / 'runs').glob('*-build'))[-1]
    first = (run / 'result.txt').read_text(encoding='utf8').splitlines()[0]
    print(first)
    if ' 0 errors' not in first:
        raise SystemExit((run / 'result.txt').read_text(encoding='utf8'))
    repoint(data, ack)


if __name__ == '__main__':
    main()
