"""Generate tools/edits/new1_leftover_legendaries.txt: legendaries built from 1.09's unused pieces (author's decision
2026-10-11: finish them rather than delete). Each is a copy of its closest sibling (legendary and recipes, so it keeps
the mod's naming, config categories and OP flag), with only the part that differs changed.

    python tools/edits/gen_new1_leftovers.py
"""
from pathlib import Path

OM = 'A1ALMOMOD_Legendary_'
CO = 'co_A1ALMOMOD_Legendary_'
PROP1 = 'DATA\\Properties\\[0]\\Value 1'
lines = ['# Generated by gen_new1_leftovers.py - edit that, not this file.']


def legendary(new, template, recipes, name, desc):
    """Copy a legendary and both its recipes (costly + FREE), point the recipes at the copy, set name and text."""
    lines.extend([
        f'rec.copy | {OM}{template} | {OM}{new}',
        f'text.set | {OM}{new} | FULL | {name}',
        f'text.set | {OM}{new} | DESC | {desc}',
        f'rec.copy | {CO}{recipes} | {CO}{new}',
        f'rec.copy | {CO}{recipes}FREE | {CO}{new}FREE',
        f'field.set | {CO}{new} | CNAM | @{OM}{new}',
        f'field.set | {CO}{new}FREE | CNAM | @{OM}{new}',
    ])


def enchantment(new, template, mgef=None, magnitude=None, name=None):
    """Copy an enchantment, optionally swapping its first effect and magnitude."""
    lines.append(f'rec.copy | {template} | {new}')
    if name:
        lines.append(f'text.set | {new} | FULL | {name}')
    if mgef:
        lines.append(f'field.set | {new} | Effects\\[0]\\EFID | @{mgef}')
    if magnitude is not None:
        lines.append(f'field.set | {new} | Effects\\[0]\\EFIT\\Magnitude | {magnitude}')


def perk_effect(new, template, perk, name):
    """Copy a 'Perk to Apply' magic effect and point it at another perk."""
    lines.extend([f'rec.copy | {template} | {new}', f'text.set | {new} | FULL | {name}',
                  f'field.set | {new} | Magic Effect Data\\DATA\\Perk to Apply | @{perk}'])


# --- Lobbin' mines: the author's "lobber variant of mines" note; the lobbed-mine projectiles were never used ---
for mine in ('Frag', 'Cryo', 'Nuke', 'Plasma', 'Pulse'):
    new = f'Weapon_Lobbing_Variant_Mine_{mine}'
    legendary(new, 'Weapon_Lobbing_Base_Impact_Base', 'Weapon_Lobbing_Base_Impact_Base', f"CLM: Lobbin' ({mine} Mine)",
              f'Your weapon is converted into a mine lobber: every shot lobs a live {mine.lower()} mine that arms where '
              f'it lands. Your ammo does not change.')
    lines.append(f'field.set | {OM}{new} | {PROP1} | @A1ALMPROJ_Variant_Type_Lobber_Mine_{mine}Mine')

# --- Hurtin' (1000%): top of the Hurtin' family (the unused 1000% enchantment did the same through a perk) ---
legendary('Weapon_DamageBoost_10x', 'Weapon_DamageBoost_5x', 'Weapon_DamageBoost_5x', "CLM: Hurtin' (1000%)",
          "Your weapon's damage is boosted by 1000%.")
lines.append(f'prop.set | {OM}Weapon_DamageBoost_10x | AttackDamage | MUL+ADD | 10')
for dt in ('dtCryo', 'dtElectrical', 'dtEnergy', 'dtFire', 'dtPhysical', 'dtPoison', 'dtRadiationExposure',
           'dtRadiationIngestion'):
    lines.append(f'prop.set | {OM}Weapon_DamageBoost_10x | DamageTypeValues[{dt}] | MUL+ADD | 10')

# --- Instant Killin': the unused "Instant killing" perk (x9999 damage), through the 1000% enchantment's chain ---
perk_effect('A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_InstantKill',
            'A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_Fortify_WeaponDamage_1000P',
            'A1ALMPERK_Legendary_Weapon_InstantKill', 'CLM Perk: Instant Killing')
enchantment('A1ALMEnch_Constant_Effect_Custom_Effect_InstantKill',
            'A1ALMEnch_Constant_Effect_Beneficial_Increase_WeaponDamage_1000P',
            mgef='A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_InstantKill', name='CLM: Instant Killing')
legendary('Weapon_InstantKilling', 'Weapon_Burning', 'Weapon_Cheaters', "CLM: Instant Killin'",
          'Your attack damage, no matter the method used, is boosted to game-breaking levels: almost anything dies in '
          'one hit. It takes a will of a giant not to use this.')
lines.append(f'field.set | {OM}Weapon_InstantKilling | {PROP1} | @A1ALMEnch_Constant_Effect_Custom_Effect_InstantKill')

# --- Medic's: unused "Heal targets" (on hit) + "Reduce Damage (50%)" (constant) ---
legendary('Weapon_Medics', 'Weapon_Chilling', 'Weapon_Vampiric', "CLM: Medic's",
          'Your shots heal whoever they hit by 50 health, but your weapon deals 50% less damage. Patch up your '
          'companions in the middle of a fight.')
lines += [f'field.set | {OM}Weapon_Medics | {PROP1} | @A1ALMEnch_FaF_Contact_Custom_Effect_Beneficial_Heal',
          f'prop.add | {OM}Weapon_Medics | Enchantments | ADD | 431 | {OM}Weapon_Medics | '
          f'@A1ALMEnch_Constant_Effect_Detrimental_Effect_Reduce_WeaponDamage_50P']

# --- Overchargin': the unused energy hit from the Rainman's draft ---
legendary('Weapon_Overcharging', 'Weapon_Chilling', 'Weapon_ThorBlessed', "CLM: Overchargin'",
          'Your hits overcharge your targets, dealing 50 extra energy damage.')
lines += [f'field.set | {OM}Weapon_Overcharging | {PROP1} | @A1ALMEnch_FaF_Contact_Target_Hostile_SplitterSpawn_Energy_DoT',
          'text.set | A1ALMEnch_FaF_Contact_Target_Hostile_SplitterSpawn_Energy_DoT | FULL | CLM: Overchargin\'']

# --- VATS Penetratin': the unused VATS-penetrate enchantment (hidden Penetrator perk) ---
legendary('Weapon_VATSPenetrating', 'Weapon_Burning', 'Weapon_VATasticallyPenetrating', "CLM: VATS Penetratin'",
          'In V.A.T.S., your shots go through cover: you can target enemies behind objects, like the Penetrator perk.')
lines.append(f'field.set | {OM}Weapon_VATSPenetrating | {PROP1} | '
             f'@A1ALMEnch_Constant_effect_Beneficial_Increase_VATSPenetrate_100P')

# --- armour: Quick Hands (50%): the unused reload-speed effect ---
enchantment('A1ALMEnch_Fortify_Effect_ReloadSpeed_50', 'A1ALMEnch_Fortify_Effect_JumpHeightMult_100',
            mgef='A1ALMMGEF_Fortify_Effect_Reload_Speed_Mult', magnitude=0.5,
            name='CLM: Fortify Effect [50% Reload Speed]')
legendary('Armor_PerkV_Fortify_ReloadSpeed_50', 'Armor_PerkV_Fortify_Jumpy_100', 'Armor_PerkV_Fortify_Jumpy_100',
          'CLM: Quick Hands (50%)', 'You reload 50% faster.')
lines.append(f'field.set | {OM}Armor_PerkV_Fortify_ReloadSpeed_50 | {PROP1} | @A1ALMEnch_Fortify_Effect_ReloadSpeed_50')

# --- armour: Marathon Runnin': the unused 75% sprint perk ---
perk_effect('A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_SprintReduceAPCost_75P',
            'A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_VatsPenetrate_100P',
            'A1ALMPERK_Legendary_Hidden_Armor_SprintReduceAPCost_75P', 'CLM Perk: Reduced Sprint Cost (75%)')
enchantment('A1ALMEnch_Constant_Effect_Custom_Effect_SprintReduceAPCost_75P',
            'A1ALMEnch_Constant_effect_Beneficial_Increase_VATSPenetrate_100P',
            mgef='A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_SprintReduceAPCost_75P', name="CLM: Marathon Runnin'")
legendary('Armor_PerkV_MarathonRunning', 'Armor_PerkV_Fortify_Jumpy_100', 'Armor_PerkV_Fortify_Jumpy_100',
          "CLM: Marathon Runnin'", 'Sprinting uses 75% less Action Points, so you can sprint four times as far.')
lines.append(f'field.set | {OM}Armor_PerkV_MarathonRunning | {PROP1} | '
             f'@A1ALMEnch_Constant_Effect_Custom_Effect_SprintReduceAPCost_75P')

# --- armour: Focused (Brief): the unused "slow time 3s when aiming" armour perk ---
enchantment('A1ALMEnch_Constant_Effect_Custom_Effect_Time_Slow_3s',
            'A1ALMEnch_Constant_effect_Beneficial_Increase_VATSPenetrate_100P',
            mgef='A1ALMMGEF_Constant_Effect_Custom_Effect_Perk_Time_Slow_3s', name='CLM: Focused (Brief)')
legendary('Armor_PerkV_Focused_Brief', 'Armor_PerkV_Fortify_Jumpy_100', 'Armor_PerkV_Fortify_Jumpy_100',
          'CLM: Focused (Brief)', 'Time slows down for three seconds when you aim, whatever weapon you use.')
lines.append(f'field.set | {OM}Armor_PerkV_Focused_Brief | {PROP1} | @A1ALMEnch_Constant_Effect_Custom_Effect_Time_Slow_3s')

# --- armour: Stealth Boy'd: the unused permanent Stealth Boy enchantment (OP, like Ghostly (Always)) ---
legendary('Armor_Undetectable_Variant_StealthBoy', 'Armor_Undetectable_Variant_Ghostly_All',
          'Armor_Undetectable_Variant_Ghostly_All', "CLM: Stealth Boy'd",
          'A permanent Stealth Boy field: you are cloaked and undetectable at all times.')
lines.append(f'field.set | {OM}Armor_Undetectable_Variant_StealthBoy | {PROP1} | '
             f'@A1ALMEnch_Constant_Effect_Cuistom_Effect_StealthBoyBonusUndetect')

# --- spawn: the missing "Random Legendary Radroach" (its projectile and explosion already existed) ---
legendary('Weapon_Custom_Spawning_Hostile_RadroachLegendary', 'Weapon_Custom_Spawning_Hostile_RadroachRandom',
          'Weapon_Custom_Spawning_Hostile_RadroachRandom',
          'ZLM: Custom Spawning: Creature/Hostile - Random Legendary Radroach',
          'On the point of impact, it will spawn the relevant NPC, relevant to the item name.')
lines.append(f'field.set | {OM}Weapon_Custom_Spawning_Hostile_RadroachLegendary | {PROP1} | '
             f'@A1ALMPROJ_Custom_Spawning_Effect_Creature_UnfriendlyFaction_RadRoachLegendary')

out = Path(__file__).with_name('new1_leftover_legendaries.txt')
out.write_text('\n'.join(lines) + '\n', encoding='utf8')
print(f'{out.name}: {len(lines) - 1} edits')
