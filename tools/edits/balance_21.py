"""2.1 balance moves (docs/PLAN_2.1.md 3; author's decision 2026-10-13): legendaries stronger than the base game's
strongest of their kind become OP, two OP ones become balanced, and a duplicate pair loses its recipes.

    python tools/edits/balance_21.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"

OP in 2.0 means the costly and FREE recipes end with the Show OP check: the setting item carried OR its global
(tools/config/settings.py on_conds). Moving to OP appends that pair; moving to balanced removes it. Loot-mode
(_Unlocked) recipes follow when tools/loot/generate.py is re-run (they copy the costly recipe). Items players already
own keep working either way. Safe to re-run.

Duplicates: Camouflaged (Always) / (Crouch) exist twice under the same names (Armor_Camouflaged_* and
Armor_Undetectable_Variant_Camouflaged_*). The Undetectable pair stays; the other pair's recipes are deleted and its
loose mod link cleared (generate.py then prunes the loose mods), but the legendaries stay so existing gear works.
Run tools/loot/families.py, plan.py, generate.py and tools/config/picker.py afterwards.
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
OM = 'A1ALMOMOD_Legendary_'
TO_OP = [
    # weapons (33): above Two Shot's damage, Rapid x2's fire rate, extra projectiles, free ammo, nuclear blasts
    'Weapon_DamageBoost_1_5x', 'Weapon_DamageBoost_2x', 'Weapon_DevilsDue', 'Weapon_Hustling', 'Weapon_RapidFire_100P',
    'Weapon_Quicker_Variant_75P', 'Weapon_Quicker_Variant_100P', 'Weapon_Gunslangers', 'Weapon_FourShot',
    'Weapon_HighExplosive', 'Weapon_Slayer_Base', 'Weapon_Slayer_Base_Silenced', 'Weapon_BirdShootin',
    'Weapon_ShotgunSurgeons_Alpha_Basic', 'Weapon_ShotgunSurgeons_Alpha_LtBlueLaser',
    'Weapon_ShotgunSurgeons_Alpha_RedLaser', 'Weapon_ShotgunSurgeons_Alpha_Plasma', 'Weapon_ShotgunSurgeons_Beta_Plasma',
    'Weapon_ShotgunSurgeons_Beta_RedLaser', 'Weapon_ShotgunSurgeons_Beta_LtBlueLaser', 'Weapon_ShotgunSurgeons_Beta_Basic',
    'Weapon_ShockgunSurgeons', 'Weapon_ThorBlessed', 'Weapon_Overcharging', 'Weapon_AlienTechd',
    'Weapon_KeltasFactorium_Perfect', 'Weapon_SynthFactorium_Rapid', 'Weapon_SynthFactorium_Specialised',
    'Weapon_SynthFactorium_Perfect', 'Weapon_Lobbing_Variant_Mine_Nuke', 'Weapon_Mine_Variant_Sticky_NukeMine',
    'Weapon_BioReactive_Variant_Nuclear', 'Weapon_ExplosiveMelee_Variant_Nuclear',
    # armour (23): above the base game's per-piece sizes (Sentinel's 15%, Bolstering +35, Sprinter's +10%...)
    'Armor_IncreaseWeaponDamage_100P', 'Armor_IncreaseWeaponDamage_150P', 'Armor_BallisticProtection_100P',
    'Armor_BallisticProtection_150P', 'Armor_Titanium_Advanced', 'Armor_JackOfAllTrades', 'Armour_Regenerative',
    'Armor_PerkV_Fortify_Speed_50', 'Armor_PerkV_Fortify_Speed_100', 'Armor_PerkV_Fortify_Speed_150',
    'Armor_PerkV_Fortify_CombinedSpeedJump_50', 'Armor_PerkV_Fortify_CombinedSpeedJump_100',
    'Armor_PerkV_Fortify_CombinedSpeedJump_150', 'Armor_Nimble_100', 'Armor_Nimble_150', 'Armor_PerkV_Fortify_Jumpy_150',
    'Armor_PerkV_Fortify_CriticalHitChance_25P', 'Armor_SadisticBrawlers', 'Armor_PerkV_Untouchable_Paralyze',
    'Armor_PerkV_Untouchable_Pacify', 'Armor_Punching_Variant_Paralyze', 'Armor_DevilsDue',
    'Armor_ExplosiveMelee_Variant_Nuclear',
]
TO_BALANCED = ['Weapon_MajesticSwagger_Base', 'Armor_PerkV_AimStabilized_100P']
DUPLICATES = ['Armor_Camouflaged_All', 'Armor_Camouflaged_Crouch']
FN_GET_ITEM_COUNT, FN_GET_GLOBAL_VALUE = 47, 74


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    sys.path.insert(0, str(ack))
    sys.path.insert(0, str(HERE.parent / 'config'))
    from ack.plugin import Plugin
    from ack.plugin.records import Subrecord
    from settings import on_conds

    # 1. duplicates (FO4Edit): delete their recipes, clear the loose mod link
    p = Plugin.load(data / MAIN)
    dup = {p.by_edid(OM + e).formid for e in DUPLICATES}
    lines = [f'field.remove | {OM}{e} | . | LNAM' for e in DUPLICATES]
    lines += [f'rec.delete | {c.edid}' for c in p.records('COBJ')
              if c.get('CNAM') and struct.unpack('<I', c.get('CNAM').data)[0] in dup]
    if len(lines) > len(DUPLICATES):
        path = HERE / 'balance_21_duplicates.txt'
        path.write_text('# Generated by balance_21.py\n' + '\n'.join(lines) + '\n', encoding='utf8')
        r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout',
                            '600', '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
        result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
        print('duplicates:', result.splitlines()[0])
        if ' 0 errors' not in result.splitlines()[0]:
            raise SystemExit(result + r.stderr)

    # 2. OP flags on the costly and FREE recipes
    p = Plugin.load(data / MAIN)
    item, glob = p.by_edid('A1ALMSET_ShowOP').formid, p.by_edid('A1ALMSETG_ShowOP').formid
    pair = on_conds(item, glob)
    target = {p.by_edid(OM + e).formid: True for e in TO_OP} | {p.by_edid(OM + e).formid: False for e in TO_BALANCED}
    count = {True: 0, False: 0}
    for c in p.records('COBJ'):
        cn = c.get('CNAM')
        if not cn or c.edid.endswith('_Unlocked') or struct.unpack('<I', cn.data)[0] not in target:
            continue
        op = target[struct.unpack('<I', cn.data)[0]]
        subs = c.subrecords
        is_op = lambda s: s.sig == 'CTDA' and struct.unpack_from('<HxxI', s.data, 8) in (
            (FN_GET_ITEM_COUNT, item), (FN_GET_GLOBAL_VALUE, glob))
        rest = [s for s in subs if not is_op(s)]
        if op:
            last = max(i for i, s in enumerate(rest) if s.sig == 'CTDA')
            rest[last + 1:last + 1] = [Subrecord('CTDA', d) for d in pair]
        if [s.data for s in rest] != [s.data for s in subs]:
            c.subrecords[:] = rest
            c.mark_dirty()
            count[op] += 1
    p.save(data / MAIN)
    print(f'{count[True]} recipes now OP ({len(TO_OP)} legendaries), {count[False]} balanced ({len(TO_BALANCED)})')


if __name__ == '__main__':
    main()
