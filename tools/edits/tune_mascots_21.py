"""2.1: three concise-view mascots raised to their group after the weak-legendary pass (buff_weak_21.py; author's
go-ahead 2026-10-15): Elemental Strikin' 20% -> 25% per element, Untouchable (Elements) 20% -> 33% per element,
Opportunist's +40% -> +60%.

    python tools/edits/tune_mascots_21.py --ack "D:/Coding Projects/AgentCreationKit" --game "D:/Steam/steamapps/common/Fallout 4"
"""
from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = 'Custom Legendary Modifications Remade.esp'
OM = 'A1ALMOMOD_Legendary_'
GET_RANDOM = 77
TEXTS = [
    f"text.set | {OM}Weapon_ElementalStriking | DESC | Each hit has a 25% chance each to deal 20 fire, cryo, poison and "
    "electrical damage over two seconds.",
    f'text.set | {OM}Armor_PerkV_Untouchable_Elements | DESC | When hostiles attack you in melee, they have a 33% chance '
    'each to be frozen, set on fire and shocked.',
    f'text.set | {OM}Weapon_Opportunists | DESC | +60% damage on a sneak attack, against a target at full health, or '
    'while you are below half health. Only one of them counts at a time.',
]


def write_raw(data: Path, ack: Path) -> None:
    sys.path.insert(0, str(ack))
    from ack.plugin import Plugin
    from ack.plugin.records import Subrecord

    p = Plugin.load(data / MAIN)
    # Elemental Strikin': each element's GetRandomPercent < 20 -> < 25
    r = p.by_edid('A1ALMEnch_FaF_Contact_Custom_Effect_Target_Hostile_ElementalStriking')
    n = 0
    for i, s in enumerate(r.subrecords):
        if s.sig == 'CTDA' and struct.unpack_from('<H', s.data, 8)[0] == GET_RANDOM:
            d = bytearray(s.data)
            assert struct.unpack_from('<f', d, 4)[0] == 20.0
            struct.pack_into('<f', d, 4, 25.0)
            r.subrecords[i] = Subrecord('CTDA', bytes(d))
            n += 1
    assert n == 4
    r.mark_dirty()
    # Untouchable (Elements): A1ALMMGEF_OnMeleeEffect's ChanceToCast 0.2 -> 0.33
    for src in ('CryoFreeze', 'Fire', 'Electrified'):
        r = p.by_edid(f'A1ALMMGEF_Constant_Effect_OnMeleeHits_{src}_20P')
        v = bytearray(r.get('VMAD').data)
        name = b'ChanceToCast'
        at = v.index(struct.pack('<H', len(name)) + name) + 2 + len(name)
        assert v[at] == 4 and round(struct.unpack_from('<f', v, at + 2)[0], 2) == 0.2
        struct.pack_into('<f', v, at + 2, 0.33)
        r.set('VMAD', bytes(v))
        r.mark_dirty()
    # Opportunist's: x1.4 -> x1.6 (three entries, never two at once)
    r = p.by_edid('A1ALMPERK_Legendary_Hidden_Weapon_Opportunists')
    hits = [i for i, s in enumerate(r.subrecords) if s.sig == 'EPFD' and len(s.data) == 4 and
            round(struct.unpack('<f', s.data)[0], 2) == 1.4]
    assert len(hits) == 3
    for i in hits:
        r.subrecords[i] = Subrecord('EPFD', struct.pack('<f', 1.6))
    r.mark_dirty()
    p.save(data / MAIN)
    print('mascots tuned: Elemental Strikin\' 25%, Untouchable (Elements) 33%, Opportunist\'s +60%')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ack', required=True)
    ap.add_argument('--game', required=True)
    a = ap.parse_args()
    ack, data = Path(a.ack), Path(a.game) / 'Data'
    path = HERE / 'tune_mascots_21.txt'
    path.write_text('# Generated by tune_mascots_21.py - edit that, not this file.\n' + '\n'.join(TEXTS) + '\n', encoding='utf8')
    r = subprocess.run([sys.executable, '-m', 'ack', 'xedit', 'run', 'apply_edits', MAIN, '--save', '--timeout', '900',
                        '--param', f'EDITS={path}'], cwd=ack, capture_output=True, text=True)
    result = (sorted((ack / 'private' / 'runs').glob('*-apply_edits'))[-1] / 'result.txt').read_text(encoding='utf8')
    print(result.splitlines()[0])
    if ' 0 errors' not in result.splitlines()[0]:
        raise SystemExit('\n'.join(l for l in result.splitlines() if l.startswith('ERROR')) + r.stderr)
    write_raw(data, ack)


if __name__ == '__main__':
    main()
