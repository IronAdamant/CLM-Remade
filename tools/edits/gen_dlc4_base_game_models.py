"""Generate tools/edits/dlc4_base_game_models.txt: replace DLC *models* (art referenced by path) with base-game ones.

Record references to DLC forms show up as masters; model paths do not, so legendaries using DLC art looked
DLC-free while still needing the DLC's archives. This lists every CLM record using one of the DLC models below and
swaps in the base-game model chosen for it. Re-run after editing the tables:

    python tools/edits/gen_dlc4_base_game_models.py --plugin "<Data>/Custom Legendary Modifications Remade.esp"
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / 'AgentCreationKit'))
from ack.plugin import Plugin  # noqa: E402

MODELS = {  # DLC model -> base-game model
    r'DLC04\Weapons\RaiderGrenades\NukeGrenadeCherryProjectile.nif': r'Weapons\Grenade\NukeGrenadeProjectile.nif',
    r'DLC04\Weapons\RaiderGrenades\NukeGrenadeProjectile.nif': r'Weapons\Grenade\NukeGrenadeProjectile.nif',
    r'DLC01\Effects\SentryFlamerProjectile.nif': r'Effects\Rocket01Projectile.nif',
    r'DLC01\Weapons\LightningGun\LightningGunBeamSizzle.nif': r'Traps\ElectricalTrap\ElectricalTrapBeam.nif',
    r'DLC04\Weapons\RaiderGrenades\FrenzyGrenadeProjectile.nif': r'Weapons\Grenade\GASGrenadeProjectile.nif',
    r'DLC04\Weapons\PaddleBall\PaddleBallAmmo.nif': r'Weapons\Grenade\NukeGrenadeProjectile.nif',
    r'DLC01\Weapons\LightningGun\LightningGunChainExplosion.nif': r'Effects\ElectricalExplosionSmall.nif',
}

# Nuka-Infused explosions, rebuilt from base-game grenade explosions; each keeps its own damage, radius and force.
NUKA = {  # flavour: (model, light, sound, impact data set, image space modifier)
    'Quantum': (r'Effects\ExplosionGrenadeEmp.nif', 'ExplosionLightGrenadeWhite', 'FXExplosionGrenadeEMP',
                'EXPGenericImpactSet', 'ExplosionGrenadeFragImod'),
    'Cherry': (r'Effects\ExplosionGrenadeFrag.nif', 'ExplosionLightGrenadeWhite', 'FXExplosionConvMed',
               'EXPGenericImpactSet', 'ExplosionGrenadeFragImod'),
    'Cola': (r'Effects\ExplosionFireExtinguisher01.nif', 'ExplosionLightGrenadeWhite', 'FXExplosionFireExtinguisher',
             'EXPGenericImpactSet', 'ExplosionGrenadeFragImod'),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--plugin', required=True)
    a = ap.parse_args()
    p = Plugin.load(a.plugin)
    out = ['# DLC independence: records that used DLC models (art by path) now use base-game ones.',
           '# Generated by tools/edits/gen_dlc4_base_game_models.py - edit the tables there, not this file.',
           '# Model swaps:']
    out += [f'#   {k}  ->  {v}' for k, v in MODELS.items()]
    for r in p.records():
        m = r.get('MODL')
        if m and m.zstring in MODELS:
            out += [f'field.set | {r.edid} | Model\\MODL | {MODELS[m.zstring]}', f'field.remove | {r.edid} | Model | MODT']
    out += ['', '# Nuka-Infused explosions: Quantum = pulse grenade (blue EMP), Cherry = frag grenade (red-orange fireball),',
            '# Cola = fire extinguisher spray.']
    for flavour, (model, light, sound, impacts, imod) in NUKA.items():
        for variant in ('Base', 'Radiation'):
            e = f'A1ALMEXP_PaddleBall_Variant_{flavour}_{variant}'
            rec = p.by_edid(e)
            if rec:
                out += [f'field.set | {e} | Model\\MODL | {model}', f'field.remove | {e} | Model | MODT',
                        f'field.set | {e} | DATA\\Light | @{light}', f'field.set | {e} | DATA\\Sound 1 | @{sound}',
                        f'field.set | {e} | DATA\\Impact Data Set | @{impacts}']
                if rec.get('MNAM'):  # image space modifier is optional; only replace one that exists
                    out.append(f'field.set | {e} | MNAM | @{imod}')
    dest = Path(__file__).with_name('dlc4_base_game_models.txt')
    dest.write_text('\n'.join(out) + '\n', encoding='utf8')
    print(dest.name, sum(1 for line in out if line.startswith('field')), 'edits')


if __name__ == '__main__':
    main()
